def normative_spec(text: str) -> str:
    body = text[text.index('## 1. Finite carrier'):text.index('## 9. Implementation map')]
    for before, after in EDITORIAL_REPLACEMENTS.items():
        body = body.replace(before, after)
    body = body.replace(r'\(', '$').replace(r'\)', '$').replace(r'\[', '$$').replace(r'\]', '$$')
    return '\n'.join(line for line in body.splitlines() if line.strip())


def check(authority_dir: Path | None = None) -> dict:
    manifest = json.loads((ROOT / 'model/AUTHORITY.json').read_text())
    failures = []
    for name, expected in manifest['local_sha256'].items():
        if digest(ROOT / name) != expected:
            failures.append(f'Local contract differs: {name}')
    if authority_dir is not None:
        for name, expected in manifest['authority_sha256'].items():
            if digest(authority_dir / name) != expected:
                failures.append(f'Supplied authority differs: {name}')
        if normative_spec((ROOT / 'model/SPEC.md').read_text()) != normative_spec(
                (authority_dir / 'SPEC.md').read_text()):
            failures.append('Specification sections 1–8 differ from the supplied authority')
    if failures:
        raise ValueError('\n'.join(failures))
    return {'all_passed': True, 'candidate': manifest['candidate'],
            'local_contract_checked': True,
            'external_authority_compared': authority_dir is not None}

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--authority-dir', type=Path)
    args = parser.parse_args()
    try:
        print(json.dumps(check(args.authority_dir), indent=2, sort_keys=True))
    except (ValueError, KeyError, OSError) as exc:
        parser.exit(1, f'{exc}\n')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
