def canonical(x):return json.dumps(x,sort_keys=True,indent=2)+'\n'
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def verify_freeze():
    p=json.loads((HERE/'PREREG.json').read_text())
    for name,digest in p['files'].items():
        if sha(HERE/name)!=digest:raise ValueError('freeze mismatch: '+name)

def rational_log_one_minus(x,terms=80):
    lo=sum((x**k/F(k) for k in range(1,terms+1)),F(0))
    hi=lo+x**(terms+1)/(F(terms+1)*(1-x))
    return lo,hi

