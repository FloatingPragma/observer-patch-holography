"""Supplied Fourier/tree preparation and honest continuing record apparatus.

These gates are added resources, not generated by the native C/E instrument.
Large fibers have an exact coordinate prescription; dense states are tiny controls.
"""
import math
import numpy as np
from .uniform_native import UniformFiberReduction
from .modular_native import LocalCoarseModular


class FiberPreparation:
    def __init__(self, construction, modulus=6):
        self.reduced=UniformFiberReduction(construction, modulus)
        self.construction=construction; self.modulus=modulus
        self.n=self.reduced.n; self.edges=self.reduced.half_edges
        seen={0}; self.parent={}; queue=[0]; tree=set()
        for v in queue:
            for w,e in self.reduced.adjacency[v]:
                if w not in seen:
                    seen.add(w); queue.append(w); self.parent[w]=(v,e); tree.add(e)
        self.order=queue
        self.chords=tuple(e for e in range(len(self.edges)) if e not in tree)

    def record_word(self, position, coordinates):
        """Unique F with div F=e0-e_position and specified non-tree residues."""
        if type(position) is not int or not 0<=position<self.n:raise ValueError('invalid position')
        coordinates=tuple(coordinates)
        if len(coordinates)!=len(self.chords) or any(type(x) is not int or not 0<=x<self.modulus for x in coordinates):raise ValueError('invalid cycle coordinates')
        f=[0]*len(self.edges); residual=[int(v==0)-int(v==position) for v in range(self.n)]
        for e,x in zip(self.chords,coordinates):
            f[e]=x; a,b=self.edges[e]; residual[a]-=x; residual[b]+=x
        for v in reversed(self.order[1:]):
            p,e=self.parent[v]; a,b=self.edges[e]
            x=residual[v] if a==v else -residual[v]
            f[e]=x%self.modulus; residual[p]+=residual[v]; residual[v]=0
        if residual[0]%self.modulus:raise ValueError('inconsistent Gauss source')
        return tuple(x%self.modulus for x in f)

    def resources(self):
        return {'architecture':'added_modular_Fourier_and_reversible_addition_gates',
                'cycle_qudits':len(self.chords),'record_qudits':len(self.edges),
                'qudit_dimension':self.modulus,'fiber_cardinality':self.modulus**len(self.chords),
                'success_probability':1,'failure_probability':0,
                'failure_scope':'ideal declared unitary gates only; hardware noise not modeled',
                'native_only_preparation':False,
                'recipe':['Initialize record ancillas at zero.',
                          'Apply exact dimension-N Fourier to each free cycle register.',
                          'Reversibly add cycle residues to non-tree half edges and solve tree residues controlled by position.',
                          'Uncompute cycle work registers from non-tree records.'],
                'gate_count_claim':None}

    def tiny_isometry(self, max_states=4096):
        if type(max_states) is not int or max_states<1:raise ValueError('invalid state budget')
        if self.n*self.modulus**len(self.chords)>max_states:raise ValueError('dense control exceeds state budget')
        import itertools
        full=LocalCoarseModular(self.construction,self.modulus)
        v=np.zeros((full.n,self.n),complex)
        for pos in range(self.n):
            for coordinates in itertools.product(range(self.modulus),repeat=len(self.chords)):
                v[full.index[(pos,self.record_word(pos,coordinates))],pos]=1/math.sqrt(self.modulus**len(self.chords))
        return full,v

    def record_measurement(self, rho, half_edge, max_states=4096):
        """Execute full record PVM, preserving every complete poststate for continuation.

        Compression gives terminal effects only. No projection back into the uniform
        code, discarded complement, or reduced subsequent evolution is performed.
        """
        if type(half_edge) is not int or not 0<=half_edge<len(self.edges):raise ValueError('invalid half edge')
        rho=self.reduced.density(rho); full,v=self.tiny_isometry(max_states)
        lifted=v@rho@v.conj().T; projector=v@v.conj().T; outputs=[]
        for residue in range(self.modulus):
            mask=np.array([state[1][half_edge]==residue for state in full.states])
            branch=lifted*mask[:,None]*mask[None,:]
            probability=float(np.trace(branch).real)
            code_weight=float(np.trace(projector@branch).real)
            outputs.append({'residue':residue,'probability':probability,
                            'code_weight':code_weight,'complement_weight':probability-code_weight,
                            'poststate_subnormalized':branch})
        return full,outputs

    def closed_cut_measurement(self,rho,vertices):
        """Whole-charge diagonal PVM preserves code; branches are subnormalized."""
        rho=self.reduced.density(rho); vertices=tuple(vertices)
        if any(type(v) is not int or not 0<=v<self.n for v in vertices):raise ValueError('invalid cut')
