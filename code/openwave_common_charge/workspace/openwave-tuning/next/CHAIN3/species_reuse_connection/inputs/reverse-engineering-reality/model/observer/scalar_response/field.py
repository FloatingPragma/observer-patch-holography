"""Full-mode free-scalar hardware and a centered quantum readout.

The action, vacuum, field control and model time are declared reversible
hardware. They are not generated by the dissipative native repair channel.
The grid, mass form and compact smearings implement the definitions in
code/source_scalar_packet/source_common_scalar.py, with an independent
edge-energy assembly and floating spectral evaluation. No result receipt is
used as an outcome-probability oracle. Floating calculations are diagnostics;
the parent's separate rational certificate bounds the mathematical model.

All (q-1)^3 oscillator modes contribute. The main evaluator works in 2D
slices. A bounded small-system coherent-state oracle implements the quantum
instrument, including its retained outcome and conditional backaction.
"""
from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal, localcontext
from fractions import Fraction
from math import exp, fsum, isfinite, isqrt, sin
from numbers import Integral, Real

import numpy as np
from scipy.linalg import eigh_tridiagonal


CERTIFIED_Q = (13, 34, 89, 233)


def _real(value, name):
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, Real):
        raise ValueError(f"{name} must be a finite real number")
    result = float(value)
    if not isfinite(result):
        raise ValueError(f"{name} must be a finite real number")
    return result


def _current(value):
    if (isinstance(value, (bool, np.bool_)) or not isinstance(value, Integral)
            or value not in (-1, 0, 1)):
        raise ValueError("current must be one of the native integers -1, 0, 1")
    return int(value)


def _array(value, name, ndim):
    if np.ma.isMaskedArray(value):
        raise ValueError(f"{name} must not be masked")
    try:
        raw = np.asarray(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{name} must be a numeric array") from exc
    if raw.ndim != ndim or raw.dtype.kind not in "iufc":
        raise ValueError(f"{name} has the wrong numeric shape")
    if not np.all(np.isfinite(raw)):
        raise ValueError(f"{name} must be finite")
    with np.errstate(over="ignore", invalid="ignore", under="ignore"):
        result = np.array(raw, dtype=complex, copy=True)
    if not np.all(np.isfinite(result)):
        raise ValueError(f"{name} exceeds the numerical representation")
    if (np.any((raw.real != 0) & (result.real == 0))
            or np.any((raw.imag != 0) & (result.imag == 0))):
        raise ValueError(f"{name} underflows the numerical representation")
    return result


def _positive_frequencies(value, size):
    raw = _array(value, "frequencies", 1)
    if raw.shape != (size,) or np.any(raw.imag != 0) or np.any(raw.real <= 0):
        raise ValueError("one positive real frequency per oscillator required")
    return raw.real


def _coefficients():
    """Exact sine coefficients of sin(pi*x)*(1+cos(pi*x))**8."""
    values = [Fraction(0)] * 10
    values[1] = Fraction(1)
    for _ in range(8):
        updated = list(values)
        for index in range(1, 10):
            if index + 1 < 10:
                updated[index + 1] += values[index] / 2
            if index > 1:
                updated[index - 1] += values[index] / 2
        values = updated
    norm_squared = sum(value * value for value in values[1:])
    return np.array([float(value) for value in values[1:]]) / np.sqrt(float(norm_squared))


def _grid(q):
    """Evaluate the exact Q(phi) addresses before converting to binary64."""
    with localcontext() as context:
        context.prec = 70
        phi = (1 + Decimal(5).sqrt()) / 2
        addressed = []
        for b in range(q):
            a = -((b + isqrt(5 * b * b)) // 2)
            addressed.append((Decimal(a) + Decimal(b) * phi, (a, b)))
        addressed.sort()
        points = [value for value, _ in addressed] + [Decimal(1)]
        gaps = [right - left for left, right in zip(points, points[1:])]
        weights = [(left + right) / 2 for left, right in zip(gaps, gaps[1:])]
        return (tuple(pair for _, pair in addressed),
                np.array(list(map(float, points))), np.array(list(map(float, gaps))),
                np.array(list(map(float, weights))))


class ScalarField:
    """Declared massive Dirichlet scalar action on the golden tensor grid.

    q is the one-axis cell count. Only CERTIFIED_Q carries the existing
    spatial certificate; smaller q values are useful independent controls.
    The one-axis stiffness is assembled from local edge energies, and all
    three-axis frequencies are sqrt(1+lambda_a+lambda_b+lambda_c).
    """

    def __init__(self, q):
        if (isinstance(q, (bool, np.bool_)) or not isinstance(q, Integral)
                or not 2 <= q <= 233):
            raise ValueError("q must be an integer from 2 to 233")
        self.q = int(q)
        self.mode_count = (self.q - 1) ** 3
        self.addresses, self.points, self.gaps, self.weights = _grid(self.q)
        if np.any(self.gaps <= 0) or np.any(self.weights <= 0):
            raise ArithmeticError("the declared golden grid must be strictly ordered")
        # Each adjacent edge contributes (u_right-u_left)^2/h. The two
        # boundary values are zero. Normalize the form by the diagonal mass.
        self.stiffness_diagonal = 1 / self.gaps[:-1] + 1 / self.gaps[1:]
        self.stiffness_off_diagonal = -1 / self.gaps[1:-1]
        diagonal = self.stiffness_diagonal / self.weights
        off = self.stiffness_off_diagonal / np.sqrt(self.weights[:-1] * self.weights[1:])
        self.laplacian_eigenvalues, self.eigenvectors = eigh_tridiagonal(diagonal, off)
        if np.any(self.laplacian_eigenvalues <= 0):
            raise ArithmeticError("positive Dirichlet stiffness expected")
        x = self.points[1:-1]
        modes = np.sqrt(2) * np.sin(np.pi * np.outer(np.arange(1, 10), x))
        coefficients = _coefficients()
        self.preparation_profile = (coefficients @ modes) * (x < .45)
        self.detector_profile = ((coefficients * (-1.) ** np.arange(9)) @ modes) * (x > .55)
        self.transverse_profile = modes[0]
        weighted_transform = self.eigenvectors.T * np.sqrt(self.weights)[None, :]
        self.preparation_modes = weighted_transform @ self.preparation_profile
        self.detector_modes = weighted_transform @ self.detector_profile
        self.transverse_modes = weighted_transform @ self.transverse_profile

    def response(self, time, current=1, gamma=4.0):
        """Compute a single centered readout after a signed momentum kick.

        Phi(g)=sum g_k(a_k+a_k^dagger)/sqrt(2*omega_k). Its vacuum variance
        is sum g_k^2/(2*omega_k), while the kick gives the mean
        current*gamma*sum f_k*g_k*sin(omega_k*time)/omega_k.
        """
        time, gamma, current = _real(time, "model time"), _real(gamma, "gamma"), _current(current)
        eigenvalues = self.laplacian_eigenvalues
        transverse_squared = np.outer(self.transverse_modes ** 2, self.transverse_modes ** 2)
        frequency_base = 1 + eigenvalues[:, None] + eigenvalues[None, :]
        means, variances = [], []
        for eigenvalue, f, g in zip(eigenvalues, self.preparation_modes, self.detector_modes, strict=True):
            omega = np.sqrt(frequency_base + eigenvalue)
            variances.append(float(np.sum(g * g * transverse_squared / (2 * omega))))
            means.append(float(np.sum(f * g * transverse_squared * np.sin(omega * time) / omega)))
        mean = current * gamma * fsum(means)
        variance = fsum(variances)
        if not isfinite(mean) or not isfinite(variance):
            raise ArithmeticError("unresolved floating scalar response")
        visibility = exp(-variance / 2)
        signal = visibility * sin(mean)
        plus, minus = (1 + signal) / 2, (1 - signal) / 2
        if not all(isfinite(value) for value in (mean, variance, visibility, plus, minus)):
            raise ArithmeticError("unresolved floating scalar response")
        return {"q": self.q, "mode_count": self.mode_count, "model_time": time,
                "current": current, "gamma": gamma, "mean": mean,
                "vacuum_variance": variance, "visibility": visibility,
                "signal": signal, "plus_probability": plus, "minus_probability": minus}

    def mode_data(self, max_modes=32768):
        """Materialize all modes only for a bounded small-system oracle."""
        if (isinstance(max_modes, (bool, np.bool_)) or not isinstance(max_modes, Integral)
                or not 1 <= max_modes <= 32768 or self.mode_count > max_modes):
            raise ValueError("small-state mode budget exceeded (maximum 32768)")
        eigenvalues = self.laplacian_eigenvalues
        omega = np.sqrt(1 + eigenvalues[:, None, None] + eigenvalues[None, :, None]
                        + eigenvalues[None, None, :]).reshape(-1)
        transverse = np.outer(self.transverse_modes, self.transverse_modes)
        preparation = (self.preparation_modes[:, None, None] * transverse).reshape(-1)
        detector = (self.detector_modes[:, None, None] * transverse).reshape(-1)
        return {"omega": omega, "preparation": preparation, "detector": detector,
                "field_vector": detector / np.sqrt(2 * omega)}

    def prepared_state(self, time, current=1, gamma=4.0, max_modes=32768):
        """Exact coherent-state formula evaluated on the small mode oracle."""
        time, gamma, current = _real(time, "model time"), _real(gamma, "gamma"), _current(current)
        data = self.mode_data(max_modes=max_modes)
        alpha = (1j * current * gamma * data["preparation"] / np.sqrt(2 * data["omega"])
                 * np.exp(-1j * data["omega"] * time))
        return CoherentSum(alpha[None, :], [1])

    def branch_descriptor(self, time, outcome, current=1, gamma=4.0):
        """Compact terminal post-read state, without allocating a Fock vector.

        Terms are D(-i beta/2)|alpha> and D(+i beta/2)|alpha>, where alpha
        is the evolved prepared coherent state and beta=g/sqrt(2*omega).
        Their inner product is exp(-variance/2+i*mean). Specifying these
        displaced states includes their Weyl phases; they must not be
        replaced by phase-free coherent amplitudes alpha +/- i*beta/2.
        """
        outcome = _outcome(outcome)
        response = self.response(time, current=current, gamma=gamma)
        probability = response["plus_probability" if outcome == 1 else "minus_probability"]
        if probability <= 0:
            raise ArithmeticError("zero-probability branch has no conditional state")
        overlap = response["visibility"] * np.exp(1j * response["mean"])
        scale = 1 / (2 * np.sqrt(probability))
        coefficients = np.array([scale, -1j * outcome * scale])
        gram = np.array([[1, overlap], [overlap.conjugate(), 1]])
        norm = float(np.vdot(coefficients, gram @ coefficients).real)
        return {"outcome": outcome, "probability": probability,
                "weyl_half_shifts": [-.5, .5],
                "coefficients": [[float(scale), 0.], [0., float(-outcome * scale)]],
                "gram": [[[1., 0.], [float(overlap.real), float(overlap.imag)]],
                         [[float(overlap.real), float(-overlap.imag)], [1., 0.]]],
                "conditional_norm_squared": norm,
                "basis": "D(i*s*beta)|alpha(t)>; beta=g/sqrt(2*omega)",
                "model_time": response["model_time"], "current": response["current"],
                "gamma": response["gamma"], "q": self.q}


def _outcome(value):
    if (isinstance(value, (bool, np.bool_)) or not isinstance(value, Integral)
            or value not in (-1, 1)):
        raise ValueError("the retained outcome must be the integer -1 or +1")
    return int(value)


@dataclass(frozen=True)
class CoherentSum:
    """Small exact-form finite superposition of normalized coherent states.

    Amplitudes have shape (terms, modes). Coefficients carry all Weyl phases.
    Inner products and conditional states use coherent-state Gram matrices;
    no oscillator occupation cutoff or Gaussian post-measurement assumption
    is made. Overflow and unresolved normalization are rejected; these checks
    do not certify roundoff for arbitrary ill-conditioned superpositions.
    """

    amplitudes: np.ndarray
    coefficients: np.ndarray

    def __post_init__(self):
        amplitudes = _array(self.amplitudes, "coherent amplitudes", 2)
        coefficients = _array(self.coefficients, "coherent coefficients", 1)
        if (not 1 <= len(amplitudes) <= 128 or not 1 <= amplitudes.shape[1] <= 32768
                or coefficients.shape != (len(amplitudes),)):
            raise ValueError("bounded coherent terms and one coefficient per term required")
        amplitudes.setflags(write=False)
        coefficients.setflags(write=False)
        object.__setattr__(self, "amplitudes", amplitudes)
        object.__setattr__(self, "coefficients", coefficients)

    def gram(self, other=None):
        other = self if other is None else other
        if not isinstance(other, CoherentSum) or self.amplitudes.shape[1] != other.amplitudes.shape[1]:
            raise ValueError("coherent states must have the same mode count")
        result = np.empty((len(self.amplitudes), len(other.amplitudes)), complex)
        for i, alpha in enumerate(self.amplitudes):
            for j, beta in enumerate(other.amplitudes):
                with np.errstate(over="ignore", invalid="ignore"):
                    difference = alpha - beta
                    distance_squared = np.vdot(difference, difference).real
                    phase = np.vdot(alpha, beta).imag
                if not isfinite(distance_squared) or not isfinite(phase):
                    raise ArithmeticError("unresolved floating coherent-state overlap")
                result[i, j] = np.exp(-distance_squared / 2 + 1j * phase)
        return result

    def inner(self, other):
        gram = self.gram(other)
        with np.errstate(over="ignore", invalid="ignore"):
            value = complex(self.coefficients.conj() @ gram @ other.coefficients)
        if not isfinite(value.real) or not isfinite(value.imag):
            raise ArithmeticError("unresolved floating coherent-state inner product")
        return value

    def norm_squared(self):
        norm = self.inner(self)
        if abs(norm.imag) > 1e-10 or norm.real < -1e-12:
            raise ArithmeticError("invalid floating coherent-state norm")
        return max(0., norm.real)

    def normalized(self):
        norm = self.norm_squared()
        if norm <= 1e-14:
            raise ArithmeticError("coherent-state norm is zero or numerically unresolved")
        normalized = CoherentSum(self.amplitudes, self.coefficients / np.sqrt(norm))
        if abs(normalized.norm_squared() - 1) > 1e-10:
            raise ArithmeticError("coherent-state normalization is numerically unresolved")
        return normalized

    def evolve(self, omega, time):
        omega = _positive_frequencies(omega, self.amplitudes.shape[1])
        time = _real(time, "model time")
        # The common vacuum-energy phase is absent from every prediction.
        return CoherentSum(self.amplitudes * np.exp(-1j * omega * time), self.coefficients)

    def displaced(self, shift):
        shift = _array(shift, "Weyl displacement", 1)
        if shift.shape != (self.amplitudes.shape[1],):
            raise ValueError("one displacement per oscillator required")
        phases = np.exp(1j * np.imag(np.sum(shift * self.amplitudes.conj(), axis=1)))
        return CoherentSum(self.amplitudes + shift, self.coefficients * phases)

    def centered_instrument(self, field_vector, outcome):
        """Return (Born probability, normalized conditional quantum state).

        K_y = [D(-i beta/2)-i*y*D(+i beta/2)]/2, with real beta. Its two
        complementary outcomes satisfy sum_y K_y^dagger K_y=I. The outcome
        remains an external classical record; this method never postselects
        a preferred sign or discards the other branch from the experiment.
        """
        outcome = _outcome(outcome)
        beta = _array(field_vector, "field vector", 1)
        if beta.shape != (self.amplitudes.shape[1],) or np.any(beta.imag != 0):
            raise ValueError("one real field coefficient per oscillator required")
        norm = self.norm_squared()
        if abs(norm - 1) > 1e-10:
            raise ValueError("a normalized premeasurement state is required")
        minus, plus = self.displaced(-.5j * beta), self.displaced(.5j * beta)
        branch = CoherentSum(np.concatenate((minus.amplitudes, plus.amplitudes)),
                             np.concatenate((minus.coefficients / 2,
                                             -1j * outcome * plus.coefficients / 2)))
        probability = branch.norm_squared()
        return probability, branch.normalized()
