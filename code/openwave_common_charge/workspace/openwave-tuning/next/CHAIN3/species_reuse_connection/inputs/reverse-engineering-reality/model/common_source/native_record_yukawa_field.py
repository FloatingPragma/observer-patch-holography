"""A record inverse and Weyl-action handoff for the declared family protocol.

The coefficient producer is native_gauge_family_records: no laboratory mass
packet enters here.  Its three Hermitian family matrices couple to the actual
native invariant Higgs tensors, with the existing all-left CAR convention.
The spatial Weyl symbol, unit neutral-Higgs background, and static mean-feedback
service are declared.  This is not a construction of an interacting continuum
field theory or a computation of laboratory poles.

The static service exp(-i h X tensor Y) has an exact, finite-angle record
inverse.  Preparations and detectors are fixed coordinate vectors; no source
eigenvectors enter them.  All plus/minus/complement and survival outcomes are
retained.  This inverse is separate from the correlated finite-memory source
experiment in native_family_record_memory; it does not replace that experiment
by an averaged Hamiltonian without an averaging bound.
"""
from __future__ import annotations

import json
import math

import numpy as np
from scipy.linalg import expm

from . import native_gauge_family_records as gates
from .chiral_candidate import kinetic

PULSE_ANGLE = 1 / 4
ANGLE_DOMAIN = (1 / 16, 1 / 2)
ADMISSION = 2e-11


def _family(value):
    result = np.asarray(value, complex)
    if (result.shape != (3, 3) or not np.isfinite(result).all()
            or not np.allclose(result, result.conj().T, atol=1e-13, rtol=0)):
        raise ValueError('a finite Hermitian3-by3 family coefficient is required')
    if np.linalg.norm(result, 2) > 1 + ADMISSION:
        raise ValueError('the declared inverse branch requires norm(Y)<=1')
    return result


def _angle(value):
    if (isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, float))
            or not math.isfinite(value) or not ANGLE_DOMAIN[0] <= value <= ANGLE_DOMAIN[1]):
        raise ValueError('a resolved interaction angle in [1/16,1/2] is required')
    return float(value)


def _effects(family_input, family_output, axis):
    a, b = np.eye(6, dtype=complex)[:, family_input], np.eye(6, dtype=complex)[:, 3+family_output]
    phase = 1 if axis == 0 else 1j
    plus, minus = (a+phase*b)/np.sqrt(2), (a-phase*b)/np.sqrt(2)
    effects = [np.outer(plus, plus.conj()), np.outer(minus, minus.conj())]
    return np.stack([*effects, np.eye(6)-sum(effects)])


def forward_records(coefficient, *, angle=PULSE_ANGLE):
    """Complete fixed-basis records of the declared static effective service.

    X/Y settings each have plus, minus and complement outcomes.  Survival has
    two outcomes.  The setting labels and angle are supplied detector design,
    not inferred particle coordinates or physical clock calibration.
    The bounded angle domain keeps both contrast division and matrix arcsine
    away from their ill-conditioned endpoints in this binary64 implementation.
    """
    Y, h = _family(coefficient), _angle(angle)
    U = expm(-1j*h*np.kron(np.array([[0, 1], [1, 0]]), Y))
    probabilities, survival = np.empty((3, 3, 2, 3)), np.empty((3, 2))
    for f in range(3):
        state = U[:, f]
        probability = float(abs(state[f])**2)
        survival[f] = probability, 1-probability
        for g in range(3):
            for axis in range(2):
                probabilities[f, g, axis] = [float(np.vdot(state, E@state).real)
                                             for E in _effects(f, g, axis)]
    return {'angle': h, 'probabilities': probabilities, 'survival': survival}


def decode_records(probabilities, survival, *, angle=PULSE_ANGLE):
    """Blind exact finite-angle inverse; accepts records and detector design only.

    Write C=cos(hY), S=sin(hY).  Fixed f input has top amplitude C_ff>0
    and bottom amplitude -i S_gf.  Survival gives C_ff; the Y and X
    contrasts give -2 C_ff Re(S_gf) and +2 C_ff Im(S_gf).
    Finally Y=arcsin(S)/h on the declared norm/angle branch.

    Validation below tests algebraic consistency.  It is not a proof that
    arbitrary supplied probabilities were generated by the source; replay
    validation is separate.  No finite-shot or outward-rounding certificate
    is asserted for the binary64 computation.
    """
    raw = (np.asarray(probabilities), np.asarray(survival))
    if any(value.dtype.kind not in 'fiu' for value in raw):
        raise ValueError('real numerical detector probabilities are required')
    p, r, h = raw[0].astype(float), raw[1].astype(float), _angle(angle)
    for values, shape in ((p, (3, 3, 2, 3)), (r, (3, 2))):
        if (values.shape != shape or not np.isfinite(values).all()
                or np.min(values) < -ADMISSION or np.max(values) > 1+ADMISSION
                or np.max(abs(values.sum(axis=-1)-1)) > ADMISSION):
            raise ValueError('complete normalized nonnegative detector records are required')
    Cff = np.sqrt(np.maximum(r[:, 0], 0))
    if np.min(Cff) < math.cos(h)-ADMISSION:
        raise ValueError('survival is outside the declared inverse branch')
    contrasts = p[..., 0]-p[..., 1]
    S = ((-contrasts[:, :, 1]+1j*contrasts[:, :, 0])/(2*Cff[:, None])).T
    if np.max(abs(S-S.conj().T)) > ADMISSION:
        raise ValueError('detector records do not reconstruct a Hermitian sine matrix')
    S = (S+S.conj().T)/2
    eigenvalues, vectors = np.linalg.eigh(S)
    if np.max(abs(eigenvalues)) > math.sin(h)+ADMISSION:
        raise ValueError('sine eigenvalues lie outside the declared inverse branch')
    Y = (vectors*np.arcsin(np.clip(eigenvalues, -math.sin(h), math.sin(h))))@vectors.conj().T/h
    replay = forward_records(Y, angle=h)
    if (np.max(abs(replay['probabilities']-p)) > 10*ADMISSION
            or np.max(abs(replay['survival']-r)) > 10*ADMISSION):
        raise ValueError('detector laws fail complete static-service consistency')
    return Y


def validate_records(coefficient, records):
    """Bind the complete detector laws to this producer, rather than a digest."""
    expected = forward_records(coefficient, angle=records['angle'])
    reconstructed = decode_records(records['probabilities'], records['survival'], angle=records['angle'])
    if any(np.max(abs(np.asarray(records[key])-expected[key])) > ADMISSION
           for key in ('probabilities', 'survival')):
        raise ValueError('complete record laws differ from the declared source service')
    return reconstructed


def assemble_kernel(channels, *, component=1):
    """Couple arbitrary complex family matrices to the native Higgs maps.

    The oriented all-left coefficient is conjugate(Y), and its reverse is
    transpose, not adjoint.  These are action coefficients in a declared unit
    Higgs background.  Tensor signs and canonical matter ordering are retained.
    """
    if component not in (0, 1) or isinstance(component, bool):
        raise ValueError('one of the two Higgs tensor components is required')
    K = np.zeros((45, 45), complex)
    for row in channels.values():
        Y = np.asarray(row['Y'], complex)
        C = np.asarray(row['Higgs_components'], complex)
        L, R = np.asarray(row['left_projector']), np.asarray(row['right_projector'])
        if (Y.shape != (3, 3) or C.shape != (2, 15, 15)
                or L.shape != (15, 15) or R.shape != (15, 15)
                or not all(np.isfinite(x).all() for x in (Y, C, L, R))):
            raise ValueError('complete finite native Higgs and family data required')
        directed = np.kron(L@C[component]@R, Y.conj())
        K += directed+directed.T
    if np.max(abs(K-K.T)) > ADMISSION:
        raise ArithmeticError('all-left field action is not complex symmetric')
    return K


def dispersion_certificate(kernel, momentum=(.23, -.31, .17), *, speed=1.):
    """Complete finite Weyl symbol comparison, including zero modes/Nambu copies."""
    K = np.asarray(kernel, complex)
    speed = kinetic.coordinate_speed() if speed is None else speed
    H = kinetic.bdg_symbol(momentum, K, speed=speed)
    masses = np.linalg.svd(K, compute_uv=False)
    energies = np.sqrt(speed**2*np.dot(momentum, momentum)+masses**2)
    expected = np.sort(np.concatenate([-np.repeat(energies, 2), np.repeat(energies, 2)]))
    actual = np.linalg.eigvalsh(H)
    if H.shape != (180, 180):
        raise ValueError('the complete45-component neutral field kernel is required')
    return {'CAR_internal_dimension': 45, 'complete_Nambu_dimension': 180,
            'momentum': list(momentum), 'coordinate_speed': speed,
            'Hermiticity_error': float(np.linalg.norm(H-H.conj().T, 2)),
            'dispersion_spectral_error': float(np.max(abs(actual-expected))),
            'rest_action_singular_values': np.sort(masses).tolist(),
            'zero_action_components': int(np.count_nonzero(masses < 1e-12)),
            'parameter': 'declared model coordinate and dimensionless neutral Higgs norm1'}


def summary():
    channels = gates.candidate_channels()
    rows = []
    for name, channel in sorted(channels.items()):
        Y = _family(channel['Y'])
        records = forward_records(Y)
        recovered = validate_records(Y, records)
        values = np.linalg.eigvalsh(Y)
        rows.append({'action_channel': name, 'charge_origin': list(channel['charge_origin']),
                     'coefficient_eigenvalues': values.tolist(),
                     'coefficient_ratios': (values/values[0]).tolist(),
                     'static_record_inverse_entry_error': float(np.max(abs(recovered-Y))),
                     'complete_detector_probability_count': int(records['probabilities'].size+records['survival'].size),
                     'record_scope': 'declared static mean-feedback service, not correlated finite memory execution'})
    kernel = assemble_kernel(channels)
    checks = dispersion_certificate(kernel)
    return {'protocol_angle_exact': str(gates.PROTOCOL_ANGLE), 'channels': rows,
            'free_field_diagnostic': checks,
            'scope': {'empirical_mass_inputs_consumed': False,
                      'same_native_invariant_Higgs_tensors': True,
                      'arbitrary_complex_family_action_supported': True,
                      'fixed_detector_design_uses_coefficient_eigenvectors': False,
                      'finite_shot_uncertainty_or_outward_numerical_certificate': False,
                      'physical_clock_or_Higgs_scale_derived': False,
                      'native_source_words_for_new_interaction_compiled': False,
                      'interacting_continuum_or_laboratory_poles_derived': False}}


if __name__ == '__main__':
    print(json.dumps(summary(), indent=2, sort_keys=True, allow_nan=False))
