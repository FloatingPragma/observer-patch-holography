VECTORS = ("Wp", "Wm", "W3", "B")
SCALARS = ("h", "G0", "Gp", "Gm")
LEFT_FERMIONS = ("uL", "dL", "nuL", "eL")
RIGHT_FERMIONS = ("uR", "dR", "eR")
GHOSTS = ("cp", "cm", "c3", "cB")


def charge(label: str) -> Fraction:
    base = label[:-4] if label.endswith("_bar") else label
    q = Fraction(FIELD_TABLE[base]["charge"])
    return -q if label.endswith("_bar") else q


def triality(label: str) -> int:
    base = label[:-4] if label.endswith("_bar") else label
    t = FIELD_TABLE[base]["triality"]
    return -t if label.endswith("_bar") else t


def neutral(multiset: tuple[str, ...]) -> bool:
    return sum((charge(f) for f in multiset), Fraction(0)) == 0 and \
        sum(triality(f) for f in multiset) % 3 == 0


def multisets(pool: tuple[str, ...], size: int) -> list[tuple[str, ...]]:
    out = set()

    def recurse(prefix: tuple[str, ...], remaining: int, start: int) -> None:
        if remaining == 0:
            out.add(tuple(sorted(prefix)))
            return
        for k in range(start, len(pool)):
            recurse(prefix + (pool[k],), remaining - 1, k)

    recurse((), size, 0)
    return sorted(out)


def general_local_basis() -> list[dict[str, Any]]:
    basis: list[dict[str, Any]] = []

    def add(fields: tuple[str, ...], structure: str, flavored: bool) -> None:
        if not neutral(fields):
            return
        basis.append({
            "fields": sorted(fields),
            "structure": structure,
            "flavor_dim": 9 if flavored else 1,
        })

    for pair in multisets(VECTORS, 2):
        add(pair, "vector_bilinear_mass", False)
    for pair in multisets(SCALARS, 2):
        add(pair, "scalar_bilinear_mass", False)
    for scalar in SCALARS:
        add((scalar,), "scalar_tadpole", False)
    for size in (3, 4):
        for combo in multisets(SCALARS, size):
            add(combo, "scalar_potential", False)
    for scalar in SCALARS:
        for pair in multisets(VECTORS, 2):
            add((scalar,) + pair, "scalar_gauge_gauge", False)
    for spair in multisets(SCALARS, 2):
        for vpair in multisets(VECTORS, 2):
            add(spair + vpair, "scalar_scalar_gauge_gauge", False)
    for spair in multisets(SCALARS, 2):
        if spair[0] != spair[1]:
            for vector in VECTORS:
                add(spair + (vector,), "scalar_scalar_gauge", False)
    for triple in multisets(VECTORS, 3):
        if len(set(triple)) == 3:
            add(triple, "yang_mills_three_point", False)
    for quad in multisets(VECTORS, 4):
        for label in ("yang_mills_four_point_12_34", "yang_mills_four_point_13_24",
                      "yang_mills_four_point_14_23"):
            add(quad, label, False)
    chirality_sets = (LEFT_FERMIONS, RIGHT_FERMIONS)
    for fermions in chirality_sets:
        for f1 in fermions:
            for f2 in fermions:
                for vector in VECTORS:
                    add((f"{f1}_bar", f2, vector), "fermion_vector_current", True)
    for f_l in LEFT_FERMIONS:
        for f_r in RIGHT_FERMIONS:
            for scalar in SCALARS:
                add((f"{f_l}_bar", f_r, scalar), "fermion_scalar_yukawa", True)
                add((f"{f_r}_bar", f_l, scalar), "fermion_scalar_yukawa", True)
            add((f"{f_l}_bar", f_r), "fermion_bilinear_mass", True)
            add((f"{f_r}_bar", f_l), "fermion_bilinear_mass", True)
    for g1_label in GHOSTS:
        for g2_label in GHOSTS:
            add((f"{g1_label}_bar", g2_label), "ghost_scalar_mass", False)
            for scalar in SCALARS:
                add((f"{g1_label}_bar", g2_label, scalar), "ghost_scalar_mass", False)
            for vector in VECTORS:
                add((f"{g1_label}_bar", g2_label, vector), "ghost_gauge_derivative", False)
    return basis


def unreachable_directions(basis: list[dict[str, Any]], table_entries: list[dict[str, Any]]) -> list[dict[str, Any]]:
    reachable = {(tuple(e["fields"]), e["structure"]) for e in table_entries}
    out = []
    for direction in basis:
        key = (tuple(direction["fields"]), direction["structure"])
        if key not in reachable:
            out.append(direction)
    return out


# ---------------------------------------------------------------------------
# Gauge pole parts from the census betas
# ---------------------------------------------------------------------------


def gauge_pole_parts(matching: dict[str, Any]) -> dict[str, Any]:
    """delta g pole = (b/2) g^3 / (16 pi^2 eps), derived from
    mu-independence of the bare coupling at one loop:

    with g0 = mu^eps (g + a1/eps) and dg/dln mu = -eps g + b g^3/kappa
    (kappa = 16 pi^2), the finite part of dg0/dln mu = 0 forces
    a1 + b g^3/kappa - g da1/dg = 0; the cubic ansatz a1 = k g^3 gives
    k - 3k = -b/kappa, so k = b/(2 kappa).  The recursion is solved
    here over exact rationals, never entered as a literal."""

    coefficients = matching["gauge_betas"]["coefficients"]
    poles = {}
    for name, key in (("dg1", "b1"), ("dg2", "b2"), ("dg3", "b3")):
        b = Fraction(coefficients[key])
        # Solve k * (1 - 3) = -b for the cubic ansatz exponent 3.
        ansatz_power = 3
        k = -b / Fraction(1 - ansatz_power)
        poles[name] = {
            "pole_coefficient": str(k),
            "expression": f"({k}) * g^3 / (16*pi^2) * (1/eps)",
            "coupling_power": ansatz_power,
            "source_beta": key,
        }
    return {
        "convention": "d = 4 - 2 eps, MSbar, bare = mu^eps (renormalized + pole series)",
        "derived_from": "eft_matching_1.gauge_betas (census-derived one-loop coefficients)",
        "poles": poles,
    }


