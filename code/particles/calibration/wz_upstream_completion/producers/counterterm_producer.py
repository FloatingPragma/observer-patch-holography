#!/usr/bin/env python3
"""Workstream D: bare-substitution counterterm packet.

Contract items and their discharge state, recorded in the payload:

1. Dimensional continuation d = 4 - 2 eps with the BMHV gamma5
   prescription frozen by declaration.
2. Bare maps substituted into the complete gauge-fixed action in its
   canonical record form (the dual-derived rule table), including the
   ghost sector; the external BRST source sector is deferred to the
   Workstream G replay and recorded as open.
3. First-order expansion generated mechanically from the table: every
   counterterm monomial is the image of a bare-map generator applied
   to a table record; no counterterm vertex is entered by hand.
4. UV poles: the gauge-coupling pole parts are DERIVED here from the
   census one-loop beta coefficients of the Workstream B packet
   through the mu-independence recursion; every other pole value is a
   declared unknown bound to the FJ_DIRECT_1 target.  Item 4 is
   partially discharged and marked so.
5. The linearized Slavnov-Taylor restoration system is emitted
   structurally: the general charge-conserving local basis is
   enumerated, the counterterm-reachable subspace is computed, and the
   structurally unreachable directions (where BMHV restoration
   counterterms would live) are listed exactly; the finite restoration
   values are open, bound to FJ_DIRECT_1 and WARD_ST_NIELSEN_1.
6. Counterterm-basis rank and null space over the declared generator
   set, with the selected normalization conditions (MSbar minimal
   subtraction plus the FJ tadpole condition on dv) declared.

Bare-map conventions: parameter generators dg1, dg2, dg3, dv, dlam,
dmu2, flavor-matrix generators dYu/dYd/dYe with dagger partners, field
generators dZW (SU(2) triplet), dZB, dZGl, dZH (doublet), dZcW, dZcB,
and fermion multiplet matrices dZQL, dZuR, dZdR, dZLL, dZeR with
dagger partners (suffix d).  The gauge-fixing term is held in renormalized form, so
there is no dxi generator; that choice is recorded.  A fermion field
renormalizes as psi -> (1 + dZ/2) psi, so a barred field carries the
dagger matrix with transposed indices, and matrix products against
Yukawa couplings keep the contraction index explicit in the emitted
symbols.
"""

from __future__ import annotations

import hashlib
import json
import sys
from fractions import Fraction
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "producers"))

from vertex_format import FIELD_TABLE  # noqa: E402

TABLE_PATH = ROOT / "outputs" / "rule_table_engine_a.json"
CHECK_PATH = ROOT / "outputs" / "rule_engine_check.json"
MATCHING_PATH = ROOT / "outputs" / "eft_matching_1.json"
OUT_PATH = ROOT / "outputs" / "renormalization_ct_1.json"

PARAMETER_GENERATORS = {"g1": "dg1", "g2": "dg2", "g3": "dg3", "v": "dv", "lam": "dlam", "mu2": "dmu2"}

FIELD_Z = {
    "Wp": "dZW", "Wm": "dZW", "W3": "dZW", "B": "dZB", "Gl": "dZGl",
    "h": "dZH", "G0": "dZH", "Gp": "dZH", "Gm": "dZH",
    "cp": "dZcW", "cm": "dZcW", "c3": "dZcW", "cB": "dZcB",
}
FERMION_MULTIPLET = {
    "uL": "dZQL", "dL": "dZQL", "uR": "dZuR", "dR": "dZdR",
    "nuL": "dZLL", "eL": "dZLL", "eR": "dZeR",
}
YUKAWA_SECTORS = ("Yu", "Yd", "Ye", "Yud", "Ydd", "Yed")


def indexed(symbol: str) -> tuple[str, int, int] | None:
    if "[" not in symbol:
        return None
    base = symbol.split("[")[0]
    i_idx, j_idx = symbol[len(base):].strip("[]").split("][")
    return base, int(i_idx), int(j_idx)


def dagger_name(base: str) -> str:
    return base[:-1] if base.endswith("d") else base + "d"


def canonical_sha256(payload: Any) -> str:
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


# ---------------------------------------------------------------------------
# First-order bare-map expansion of one record
# ---------------------------------------------------------------------------


def record_flavor_symbol(monomial: dict[str, Any]) -> tuple[str, int, int] | None:
    for name, _power in monomial["powers"]:
        parsed = indexed(name)
        if parsed and parsed[0] in YUKAWA_SECTORS:
            return parsed
    return None


def ct_terms_for_record(entry: dict[str, Any]) -> list[dict[str, Any]]:
    """All first-order counterterm monomials generated by the bare map.

    Every emitted term carries the generator symbol, the residual
    coupling powers, and, for flavored records, the free generation
    binding (bar_gen, plain_gen) so the deformation coordinate is
    unambiguous."""

    fields = entry["fields"]
    structure = entry["structure"]
    terms: list[dict[str, Any]] = []

    bar_fermions = [f[:-4] for f in fields if f.endswith("_bar") and f[:-4] in FERMION_MULTIPLET]
    plain_fermions = [f for f in fields if not f.endswith("_bar") and f in FERMION_MULTIPLET]

    for monomial in entry["coefficient"]["monomials"]:
        prefactor = Fraction(monomial["prefactor"])
        powers = [tuple(p) for p in monomial["powers"]]
        flavor = record_flavor_symbol(monomial)

        def emit(value: Fraction, generator: str, residual: list[tuple[str, int]],
                 bar_gen: int | None, plain_gen: int | None) -> None:
            if value == 0:
                return
            terms.append({
                "fields": fields,
                "structure": structure,
                "generator": generator,
                "prefactor": str(value),
                "residual_powers": [list(p) for p in sorted(residual)],
                "bar_gen": bar_gen,
                "plain_gen": plain_gen,
            })

        base_bar = flavor[1] if flavor else None
        base_plain = flavor[2] if flavor else None

        # Parameter generators: d/d(param) of the coupling monomial.
        for name, power in powers:
            if name in PARAMETER_GENERATORS:
                residual = [(n, p) for n, p in powers if n != name]
                if power != 1:
                    residual.append((name, power - 1))
                emit(prefactor * power, PARAMETER_GENERATORS[name], residual, base_bar, base_plain)
            parsed = indexed(name)
            if parsed and parsed[0] in YUKAWA_SECTORS:
                residual = [(n, p) for n, p in powers if n != name]
                emit(prefactor, f"d{name}", residual, base_bar, base_plain)

        # Boson and ghost field generators: (1/2) dZ per field.
        for f in fields:
            base = f[:-4] if f.endswith("_bar") else f
            if base in FIELD_Z:
                emit(prefactor / 2, FIELD_Z[base], powers, base_bar, base_plain)

        # Fermion field generators.
        if bar_fermions or plain_fermions:
            if flavor is None:
                # Flavor-diagonal record: the barred side contributes
                # (1/2) dZd[i][j] and the plain side (1/2) dZ[i][j].
                for i in (1, 2, 3):
                    for j in (1, 2, 3):
                        for f in bar_fermions:
                            emit(prefactor / 2, f"{dagger_name(FERMION_MULTIPLET[f])}[{i}][{j}]",
                                 powers, i, j)
                        for f in plain_fermions:
                            emit(prefactor / 2, f"{FERMION_MULTIPLET[f]}[{i}][{j}]",
                                 powers, i, j)
            else:
                base, i_idx, j_idx = flavor
                residual = [(n, p) for n, p in powers if indexed(n) is None or indexed(n)[0] not in YUKAWA_SECTORS]
                for f in bar_fermions:
                    z_name = dagger_name(FERMION_MULTIPLET[f])
                    for a in (1, 2, 3):
                        # bar side: (1/2) dZd[a][i] Y[i][j], free pair (a, j)
                        emit(prefactor / 2, f"{z_name}[{a}][{i_idx}]",
                             residual + [(f"{base}[{i_idx}][{j_idx}]", 1)], a, j_idx)
                for f in plain_fermions:
                    z_name = FERMION_MULTIPLET[f]
                    for b in (1, 2, 3):
                        # plain side: Y[i][j] (1/2) dZ[j][b], free pair (i, b)
                        emit(prefactor / 2, f"{z_name}[{j_idx}][{b}]",
                             residual + [(f"{base}[{i_idx}][{j_idx}]", 1)], i_idx, b)
    return terms


# ---------------------------------------------------------------------------
# Rank and null space of the generator map
# ---------------------------------------------------------------------------


def build_matrix(terms: list[dict[str, Any]]) -> tuple[list[str], list[str], dict[tuple[int, int], Fraction]]:
    rows: dict[str, int] = {}
    columns: dict[str, int] = {}
    entries: dict[tuple[int, int], Fraction] = {}
    for term in terms:
        row_key = json.dumps({
            "fields": term["fields"],
            "structure": term["structure"],
            "residual_powers": term["residual_powers"],
            "bar_gen": term["bar_gen"],
            "plain_gen": term["plain_gen"],
        }, sort_keys=True)
        row = rows.setdefault(row_key, len(rows))
        column = columns.setdefault(term["generator"], len(columns))
        entries[(row, column)] = entries.get((row, column), Fraction(0)) + Fraction(term["prefactor"])
    row_names = [name for name, _ in sorted(rows.items(), key=lambda item: item[1])]
    column_names = [name for name, _ in sorted(columns.items(), key=lambda item: item[1])]
    return row_names, column_names, entries


def rank_and_nullspace(row_count: int, column_names: list[str],
                       entries: dict[tuple[int, int], Fraction]) -> tuple[int, list[dict[str, str]]]:
    n_cols = len(column_names)
    dense = [[Fraction(0)] * n_cols for _ in range(row_count)]
    for (r, c), value in entries.items():
        dense[r][c] = value
    pivot_cols: list[int] = []
    row = 0
    for col in range(n_cols):
        pivot = None
        for r in range(row, row_count):
            if dense[r][col] != 0:
                pivot = r
                break
        if pivot is None:
            continue
        dense[row], dense[pivot] = dense[pivot], dense[row]
        inv = 1 / dense[row][col]
        dense[row] = [x * inv for x in dense[row]]
        for r in range(row_count):
            if r != row and dense[r][col] != 0:
                factor = dense[r][col]
                dense[r] = [x - factor * y for x, y in zip(dense[r], dense[row])]
        pivot_cols.append(col)
        row += 1
        if row == row_count:
            break
    rank = len(pivot_cols)
    free_cols = [c for c in range(n_cols) if c not in pivot_cols]
    nullspace = []
    for free in free_cols:
        vector = {column_names[free]: "1"}
        for pivot_row, pivot_col in enumerate(pivot_cols):
            value = -dense[pivot_row][free]
            if value != 0:
                vector[column_names[pivot_col]] = str(value)
        nullspace.append(vector)
    return rank, nullspace


