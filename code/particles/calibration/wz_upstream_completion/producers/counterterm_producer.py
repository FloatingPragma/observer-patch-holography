def build_packet() -> dict[str, Any]:
    table = json.loads(TABLE_PATH.read_text(encoding="utf-8"))
    check = json.loads(CHECK_PATH.read_text(encoding="utf-8"))
    matching = json.loads(MATCHING_PATH.read_text(encoding="utf-8"))
    if check["status"] != "PASS" or check["table_digest"] != table["table_digest"]:
        raise SystemExit("counterterms: the rule-engine check does not certify this table")

    terms: list[dict[str, Any]] = []
    for entry in table["entries"]:
        terms.extend(ct_terms_for_record(entry))
    row_names, column_names, entries = build_matrix(terms)
    rank, nullspace = rank_and_nullspace(len(row_names), column_names, entries)

    basis = general_local_basis()
    unreachable = unreachable_directions(basis, table["entries"])
    basis_dim = sum(d["flavor_dim"] for d in basis)
    unreachable_dim = sum(d["flavor_dim"] for d in unreachable)

    packet = {
        "schema": "renormalization_ct.v1",
        "target": "RENORMALIZATION_ST_1",
        "bindings": {
            "rule_table_digest": table["table_digest"],
            "rule_engine_check": {"status": check["status"], "entry_count": check["entry_count"]},
            "eft_matching_subject": matching.get("action_subject_digest"),
        },
        "conventions": {
            "dimensional_continuation": "d = 4 - 2 eps",
            "gamma5": (
                "BMHV: gamma5 anticommutes with the four-dimensional gamma "
                "matrices and commutes with the evanescent ones; chiral "
                "vertices are four-dimensional projections; this freeze is "
                "the declared prescription for every downstream loop"
            ),
            "gauge_fixing": (
                "the gauge-fixing functions are written in renormalized "
                "fields and parameters and receive no independent dxi "
                "generator; ghost fields carry dZcW and dZcB"
            ),
            "fermion_field_map": "psi -> (1 + dZ/2) psi, barred fields carry the dagger matrix",
            "external_sources": (
                "the BRST external-source sector is not part of the record "
                "table; its counterterm structure is recomputed inside the "
                "WARD_ST_NIELSEN_1 replay and stays open here"
            ),
        },
        "generators": column_names,
        "ct_term_count": len(terms),
        "ct_terms_digest": canonical_sha256(
            sorted(terms, key=lambda item: json.dumps(item, sort_keys=True))
        ),
        "ct_matrix": {
            "rows": len(row_names),
            "columns": len(column_names),
            "rank": rank,
            "nullspace": nullspace,
            "nullspace_interpretation": (
                "the two null directions are the uniform anti-hermitian "
                "diagonal combinations dZ - dZdagger over the quark "
                "multiplets and over the lepton multiplets: global baryon- "
                "and lepton-number phase rotations, under which every "
                "record of the action is invariant"
            ),
        },
        "general_local_basis": {
            "directions": len(basis),
            "dimension_with_flavor": basis_dim,
            "unreachable_directions": len(unreachable),
            "unreachable_dimension_with_flavor": unreachable_dim,
            "unreachable": unreachable,
            "statement": (
                "the listed directions receive no counterterm from any "
                "generator of the bare map because no table record carries "
                "their field content; finite symmetry-restoring counterterms "
                "under the frozen BMHV prescription live inside this "
                "complement together with the coefficient-relation "
                "deviations inside the reachable block"
            ),
        },
        "uv_poles": {
            "gauge_sector": gauge_pole_parts(matching),
            "open_pole_values": {
                "generators": sorted(set(column_names) - {"dg1", "dg2", "dg3"}),
                "fixed_by": "FJ_DIRECT_1",
                "statement": (
                    "every non-gauge pole value is a declared unknown; this "
                    "packet refuses numeric assignments without a "
                    "FJ_DIRECT_1 receipt"
                ),
            },
        },
        "st_restoration": {
            "status": "structure_emitted_values_open",
            "fixed_by": ["FJ_DIRECT_1", "WARD_ST_NIELSEN_1"],
            "linearized_system": (
                "restoration counterterms are the solution of the "
                "linearized Slavnov-Taylor identity over the reachable "
                "block plus the unreachable complement listed above"
            ),
        },
        "normalization_conditions": {
            "scheme": "MSbar minimal subtraction for every generator",
            "tadpole": (
                "FJ condition on dv: the counterterm tadpole cancels the "
                "one-loop tadpole T_h of FJ_DIRECT_1; recorded as an "
                "equation, not a value"
            ),
        },
        "work_order_discharge": {
            "item_1_bmhv_freeze": "closed_by_declaration",
            "item_2_bare_substitution": "closed_for_the_record_table__external_sources_open",
            "item_3_first_order_no_hand_entry": "closed",
            "item_4_uv_poles": "gauge_sector_derived__remaining_values_open",
            "item_5_st_restoration": "structure_emitted__values_open",
            "item_6_rank_nullspace_normalization": "closed",
        },
        "controls": {},
    }

    controls: dict[str, Any] = {}
    mutated = json.loads(json.dumps(matching))
    mutated["gauge_betas"]["coefficients"]["b1"] = "41/5"
    controls["beta_mutation_changes_poles"] = {
        "expected_failure": True,
        "failed": gauge_pole_parts(mutated) != packet["uv_poles"]["gauge_sector"],
    }
    controls["numeric_pole_without_receipt_refused"] = {
        "expected_failure": True,
        "failed": "dlam" in packet["uv_poles"]["open_pole_values"]["generators"],
    }
    reduced_terms = [t for t in terms if t["generator"] != "dZW"]
    r_rows, r_cols, r_entries = build_matrix(reduced_terms)
    reduced_rank, _ = rank_and_nullspace(len(r_rows), r_cols, r_entries)
    controls["generator_removal_drops_rank"] = {
        "expected_failure": True,
        "failed": reduced_rank < rank,
    }
    foreign = dict(terms[0])
    foreign["generator"] = "dxi2"
    controls["foreign_generator_rejected"] = {
        "expected_failure": True,
        "failed": foreign["generator"] not in column_names,
    }
    packet["controls"] = controls

    body = {key: value for key, value in packet.items()}
    packet["packet_sha256"] = canonical_sha256(body)
    return packet


def main() -> int:
    packet = build_packet()
    OUT_PATH.write_text(json.dumps(packet, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({
        "status": "WROTE",
        "ct_terms": packet["ct_term_count"],
        "rank": packet["ct_matrix"]["rank"],
        "columns": packet["ct_matrix"]["columns"],
        "nullspace": len(packet["ct_matrix"]["nullspace"]),
        "unreachable": packet["general_local_basis"]["unreachable_directions"],
    }))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
