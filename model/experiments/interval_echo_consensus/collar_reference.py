ROUTE = ((1, 82), (10, 20), (0, 10), (10, 20))


def check_route():
    board = federation(0)
    native_seams = {tuple(sorted(edge)) for edge in board.seams}
    if not all(tuple(sorted(edge)) in native_seams for edge in ((0, 1), *ROUTE)):
        raise ValueError("A required contact is missing")
    for ports in product(range(12), repeat=2):
        loads = (ports.count(0), ports.count(1))
        for coin in (0, 1):
            occupancy = np.bincount(ports, minlength=board.n)
            occupancy[:2] = law.native_event(*loads, coin)
            expected = occupancy.copy()
            expected[[20, 82]] = expected[:2]
            expected[:2] = 0
            for a, b in ROUTE:
                occupancy[[a, b]] = occupancy[[b, a]]
            if not np.array_equal(expected, occupancy):
                raise ValueError("Auxiliary extraction disturbed a spectator port")
    return [edge for edge in board.seams if max(edge) < 12]


def source_counts(address_counts):
    counts = [0] * law.N_SRC
    entries = address_counts.tolist()
    for a, b in product(range(12), repeat=2):
        loads = ((a == 0) + (b == 0), (a == 1) + (b == 1))
        counts[law.SRC.index(loads)] += entries[a][b]
    return counts


def exact_records(counts):
    # In the incoming classical mixture, either orientation contributes half
    # its probability to each of the two parity modes of the same magnitude.
    bins = [Fraction(0)] * 5
    total = sum(counts)
    for (a, b), n in zip(law.SRC, counts, strict=True):
        d = abs(a - b)
        if d:
            bins[2*d-1] += Fraction(n, 2*total)
            bins[2*d] += Fraction(n, 2*total)
        else:
            bins[0] += Fraction(n, total)
    bypass = [p/2 for p in bins]
    even = [p if j in (0, 1, 3) else Fraction(0) for j,p in enumerate(bypass)]
    rejected = bypass[2] + bypass[4]
    accepted = sum(bypass) + sum(even)
    if accepted + rejected != 1:
        raise ValueError("Lost a public outcome")
    zero, s1, a1, s2, a2 = [(p + q) / accepted for p, q in zip(bypass, even, strict=True)]
    return dict(bypass=bypass, compared_even=even, rejected=rejected, accepted=accepted,
                populations=[zero, s1, a1, s2, a2], beta=log(s1/a1) if a1 else None,
                inferred_kappa=log(zero/s1)/log(s1/a1) if a1 else None,
                magnitude_two_ratio=s2 * zero**3 / s1**4 if s1 else None,
                parity_two_ratio=s2 * a1 / (a2 * s1) if a2*s1 else None)


def native_read(kappa, rho, exact):
    # All evolutions act on the native 99-state seam. Blank and empty embeddings
    # also check leakage into physical register states outside the proposed sectors.
    identity = np.eye(law.DIM)
    blank = identity[:, :law.N_SRC]
    empty = identity[:, np.arange(1 + law.N_LAB) * law.N_SRC + law.SRC.index((0, 0))]
    swap = np.eye(law.N_SRC)[:, [law.SRC.index((b,a)) for a,b in law.SRC]]
    even = (np.eye(law.N_SRC) + swap) / 2
    echo = law.echo()
    exchange, contrast = law.local_term_parts()
    half = expm(-1j * np.pi / 2 * (exchange + kappa * contrast))
    full = half @ half
    np.testing.assert_allclose(abs(full @ blank), blank @ swap, atol=2e-12, rtol=0)
    entrant = law.SRC.index((1, 0))
    half_hit = half @ blank[:, entrant]
    expected = (blank[:, entrant] + blank[:, law.SRC.index((0, 1))])/2
    np.testing.assert_allclose(abs(half_hit)**2, expected, atol=2e-12, rtol=0)
    signed_phase = np.array([1, *(1j if d < 0 else 1 for _, d in law.LABELS)])
    phase_write = echo @ (np.repeat(signed_phase, law.N_SRC)[:, None] * (echo @ blank))
    phase = np.diag([1j if a < b else 1 for a, b in law.SRC])
    np.testing.assert_allclose(phase_write, blank @ phase, atol=2e-12)
    analyze = half @ phase_write
    read = np.tile([a <= b for a, b in law.SRC], 1 + law.N_LAB)
    np.testing.assert_allclose(analyze.conj().T @ (read[:, None]*analyze), even, atol=2e-12)
    rewind = phase.conj().T @ blank.T @ full @ half
    selected = rewind @ (read[:, None] * analyze)
    filtered = selected @ rho @ selected.conj().T / 2
    rejected = float(np.trace((~read)[:, None] * (analyze @ rho @ analyze.conj().T)).real / 2)
    np.testing.assert_allclose(rejected, float(exact["rejected"]), atol=2e-12)

    written = (echo @ blank)[law.N_SRC:, :]
    stack = np.zeros((1+law.N_LAB, 1+law.N_LAB), complex)
    for name, branch in (("bypass", rho/2), ("compared_even", filtered)):
        joint = written @ branch @ written.conj().T
        memory = np.trace(joint.reshape(law.N_LAB, law.N_SRC, law.N_LAB, law.N_SRC), axis1=1, axis2=3)
        stack[1:, 1:] += memory
        # Extraction acts unitarily only on the other registers and makes ports 0,1 empty.
        analyzer = half @ (empty[:, 1:] * signed_phase[None, 1:])
        output = np.diag(analyzer @ memory @ analyzer.conj().T).real
        for coin in (0, 1):
            states = [1 + law.LABELS.index((coin, d)) for d in (0,-1,1,-2,2)]
            bins = output[np.array(states) * law.N_SRC + law.SRC.index((0,0))]
            np.testing.assert_allclose(bins, [float(p)/2 for p in exact[name]], atol=2e-12)
        np.testing.assert_allclose(output.sum(), np.trace(branch).real, atol=2e-12)

    block = stack[1:6, 1:6] / stack[1:6, 1:6].trace()
    np.testing.assert_allclose(np.linalg.eigvalsh(block), sorted(float(p) for p in exact["populations"]),
                               atol=2e-12, rtol=0)
    columns = empty[:, 1:6]
    for native in (exchange, contrast):
        restricted = columns.T @ native @ columns
        np.testing.assert_allclose(native @ columns, columns @ restricted, atol=2e-12)
        np.testing.assert_allclose(restricted @ block, block @ restricted, atol=2e-12)
    # Dephasing the written signs removes both parity splits.
    dephased = np.diag(np.diag(block))
    detector = half @ (columns * signed_phase[None, 1:6])
    probabilities = np.diag(detector @ dephased @ detector.conj().T).real
    for magnitude in (1,2):
        i, j = [law.N_SRC * (1 + law.LABELS.index((0,d))) for d in (-magnitude,magnitude)]
        np.testing.assert_allclose(probabilities[i], probabilities[j], atol=2e-12)


def exchange_removed_control():
    _, contrast = law.local_term_parts()
    half = expm(-4j*np.pi * contrast)
    blank = np.eye(law.DIM)[:, :law.N_SRC]
    left = blank[:, law.SRC.index((1, 0))]
    right = blank[:, law.SRC.index((0, 1))]
    hop = float(abs(np.vdot(right, half @ left))**2)
    # Incoming exchange-even (|1,0>+|0,1>)/sqrt(2). The supplied phase on
    # negative contrast gives i on |0,1>. A diagonal flight cannot recombine it.
    incoming = (left + 1j * right) / np.sqrt(2)
    selector = np.tile([a <= b for a, b in law.SRC], 1+law.N_LAB)
    accepts_even = float(np.sum(abs((half @ incoming)[selector])**2))
    np.testing.assert_allclose([hop, accepts_even], [0, 0.5], atol=2e-12, rtol=0)
    return dict(half_contact_hop_probability=0, tested_even_acceptance="1/2")


def homogeneous_flight(edges):
    # Build the one-probe sum from the native seam on blank memory. A probe
    # outside the selected seam sees its empty column.
    columns = np.eye(law.DIM)[:, [law.SRC.index(pair) for pair in ((0,0), (1,0), (0,1))]]
    exchange, contrast = law.local_term_parts()
    swap_part = np.array([[0,0,0], [0,.5,-.5], [0,-.5,.5]])
    np.testing.assert_allclose(exchange @ columns, columns @ swap_part, atol=1e-13)
    np.testing.assert_allclose(contrast @ columns, columns @ np.diag([0,1,1]), atol=1e-13)
    adjacency = np.zeros((12,12))
    for a,b in edges:
        adjacency[a,b] = adjacency[b,a] = 1
    np.testing.assert_array_equal(adjacency.sum(axis=1), 5)
    h = (5*np.eye(12) - adjacency)/2

    # With adjacency eigenvalue a and multiplicity m, transitivity gives
    # projector diagonal m/12. Applying the adjacency on the diagonal gives
    # the fixed-neighbor entry a*m/60. These sums give exact amplitudes at t.
    spectrum = np.array([5, sqrt(5), -1, -sqrt(5)])
    multiplicities = np.array([1,3,5,3])
    energies = (5-spectrum)/2
    coefficients = np.array([multiplicities/12, spectrum*multiplicities/60])
    np.testing.assert_allclose(np.linalg.eigvalsh(h), np.repeat(energies,multiplicities), atol=1e-13)

    def neighbor_slope(t):
        phase = np.exp(-1j * energies * t)
        amp = coefficients[1] @ phase
        velocity = coefficients[1] @ (-1j * energies * phase)
        return 10 * (amp.conjugate()*velocity).real

    grid = np.arange(1,3201) / 200
    slopes = np.array([neighbor_slope(t) for t in grid])
    crossing = np.flatnonzero((slopes[:-1] > 0) & (slopes[1:] < 0))[0]
    bracket = grid[crossing:crossing+2]
    t = brentq(neighbor_slope, *bracket, xtol=1e-13)
    d,e = abs(coefficients @ np.exp(-1j*energies*t))**2
    transfer = abs(expm(-1j*t*h))**2
    np.testing.assert_allclose(np.diag(transfer), d, atol=1e-13)
    np.testing.assert_allclose(transfer[adjacency == 1], e, atol=1e-13)
    np.testing.assert_allclose(transfer.sum(axis=1), 1, atol=1e-13)
    for kappa in (0, 1.5, 8):
        np.testing.assert_allclose(abs(expm(-1j*t*(h+5*kappa*np.eye(12))))**2, transfer, atol=1e-13)
    # Physical addresses are read sharply, then used for fresh two-load emission.
    source = np.array(source_counts(transfer/12))
    record = exact_records([Fraction(p) for p in source])
    native_read(8, np.diag(source), record)
    z,u,v = (8+2*d+4*e)/12, (1-d-e)/6, d/12
    np.testing.assert_allclose([float(record["magnitude_two_ratio"]), float(record["inferred_kappa"])],
                               [v*z**3/u**4, log2(z/u)], atol=1e-12, rtol=0)
    if record["parity_two_ratio"] != 1 or min(record["populations"]) <= 0:
        raise ValueError("Parity or faithful support failed for the cell flight")
    return dict(exposure_grid=[0.005, 16, 0.005], peak_bracket=bracket.tolist(),
                exposure=round(t,8), return_probability=round(d,8), fixed_neighbor_probability=round(e,8),
                neighbor_shell_probability=round(5*e,8), public_acceptance=round(float(record["accepted"]),8),
                accepted_populations=[round(float(p),8) for p in record["populations"]],
                inferred_kappa=round(record["inferred_kappa"],8), parity_two_ratio=1,
                magnitude_two_ratio=round(float(record["magnitude_two_ratio"]),8))


def isotropic_endpoint_bound(edges):
    # Exact saturation control: put remaining probability equally on five
    # neighbors. This deliberately chosen test distribution checks the bound.
    ratio = Fraction(2**8)
    d = (4*ratio - 22)/(4*ratio + 3)
    e = (1-d)/5
    kernel = np.eye(12,dtype=object)*d
    for a,b in edges:
        kernel[a,b] = kernel[b,a] = e
    record = exact_records(source_counts(kernel))
    zero,one,_,two,_ = record["populations"]
    floor = (2*ratio - 11)*ratio**3/20
    if zero/one != ratio or two*zero**3/one**4 != floor:
        raise ValueError("The isotropic saturation control disagrees with the exact bound")
    cutoff = brentq(lambda r: (2*r-11)*r**3 - 20, 5.5, 6.)
    return dict(maximum_R_at_unit_held_ratio=round(cutoff,8),
                maximum_inferred_kappa_at_unit_held_ratio=round(log2(cutoff),8),
                minimum_held_ratio_at_inferred_kappa_8=floor,
                sharp_saturation_control_return=d, sharp_saturation_control_each_neighbor=e)


def coherent_two_load_floor(edges):
    echo_columns = law.echo()[:, :law.N_SRC]
    nonzero_label = np.repeat([False, *(d != 0 for _, d in law.LABELS)], law.N_SRC)
    np.testing.assert_allclose(echo_columns.T @ (nonzero_label[:,None]*echo_columns),
                               np.diag([a != b for a,b in law.SRC]), atol=1e-13)
    states = list(combinations_with_replacement(range(12), 2))
    index = {pair:i for i,pair in enumerate(states)}
    identity = np.eye(len(states))
    counts = np.zeros(len(states), dtype=int)
    accepted = np.zeros_like(identity)
    joint = np.zeros_like(identity)
    adjacency = np.zeros((12,12), dtype=int)
    for a,b in edges:
        adjacency[a,b] = adjacency[b,a] = 1
        exchanged = {a:b, b:a}
        permutation = [index[tuple(sorted(exchanged.get(v,v) for v in pair))] for pair in states]
        # Fairly bypass or keep the even outcome. Both terms commute with |d|.
        keep = (3*identity + identity[:,permutation])/4
        nonzero = np.array([pair.count(a) != pair.count(b) for pair in states])
        counts += nonzero
        accepted += keep
        joint += nonzero[:,None]*keep
    seam_counts, multiplicities = np.unique(counts, return_counts=True)
    np.testing.assert_array_equal(seam_counts, [5,8,10])
    np.testing.assert_array_equal(multiplicities, [12,30,36])
    eye12 = np.eye(12,dtype=int)
    two_factors = (adjacency-5*eye12) @ (adjacency+eye12)
    np.testing.assert_array_equal(two_factors @ (adjacency @ adjacency - 5*eye12), 0)
    if not np.any(two_factors):
        raise ValueError("The irrational adjacency eigenspaces are absent")
    doubles = np.ix_([index[(v,v)] for v in range(12)], [index[(v,v)] for v in range(12)])
    np.testing.assert_array_equal(4*joint[doubles], 15*eye12+adjacency)
    np.testing.assert_array_equal((accepted-joint)[doubles], 25*eye12)
    floor = (15-sqrt(5))/(115-sqrt(5))
    np.testing.assert_allclose(eigvalsh(joint, accepted, subset_by_index=[0,0]), floor, atol=1e-13)
    odds = Fraction(3,2)*(Fraction(1,2**8) + Fraction(1,2**32))
    return dict(total_load=2, states=len(states), seams=len(edges),
                basis_state_counts_by_nonzero_seams=dict(zip(seam_counts.astype(str),multiplicities.tolist())),
                elementary_conditional_floor=Fraction(1,11), coherent_conditional_floor=round(floor,8),
                target_nonzero_probability=odds/(1+odds), target_beta="log(2)", target_kappa=8)


def measure():
    edges = check_route()
    counts = source_counts(np.ones((12,12), dtype=int))
    rho = np.diag(np.asarray(counts) / sum(counts))
    exact = exact_records(counts)
    variants = (-8, 0, 1.5, 8, 128)
    for kappa in variants:
        native_read(kappa, rho, exact)
    attempts = 2 * len(edges) * np.eye(12, dtype=object)
    for a,b in edges:
        attempts[a,a] -= 1
        attempts[b,b] -= 1
        attempts[a,b] += 1
        attempts[b,a] += 1
    histories = []
    for length in (0, 1, 2, 4, 8, 16):
        pairs = np.linalg.matrix_power(attempts, length)
        denominator = (2 * len(edges))**length
        if not np.all(pairs.sum(axis=1) == denominator) or not np.array_equal(pairs, pairs.T):
            raise ValueError("The fair history kernel lost total weight or reversibility")
        correlated = source_counts(pairs)
        record = exact_records(correlated)
        native_read(8, np.diag(np.asarray(correlated, dtype=float)/sum(correlated)), record)
        if length and record["magnitude_two_ratio"] < Fraction(3456,625):
            raise ValueError("The exact counts violate the all-length bound")
        histories.append(dict(steps=length, return_probability=Fraction(pairs[0,0], denominator),
                              neighbor_probability=Fraction(pairs[0,1], denominator), public_records=record))
    return dict(source_pairs=144, route=ROUTE, source_probabilities=np.diag(rho).tolist(),
                kappa_controls=variants, mode_order=["zero", "one_even", "one_odd", "two_even", "two_odd"],
                accepted_coin_probability=[0.5,0.5], public_records=exact,
                square_contrast_matches=exact["magnitude_two_ratio"] == 1,
                equal_parity_splitting_matches=exact["parity_two_ratio"] == 1,
                walk_histories=histories, all_walk_lengths_ratio_floor=Fraction(3456,625),
                independently_stopped_sharp_ratio_floor=Fraction(3456,625),
                homogeneous_neighbor_arrival=homogeneous_flight(edges),
                rotationally_invariant_two_address_bound=isotropic_endpoint_bound(edges),
                coherent_two_load_floor=coherent_two_load_floor(edges),
                exchange_removed_control=exchange_removed_control())


