"""Scalar Green functions of the compiled seam word at a patch clock reading."""
from math import prod

import numpy as np

from .gate import require


def eigenphase(angles):
    """Mobile phase in [0, pi], resolved from the nearer band endpoint."""
    k = np.asarray(angles)
    require(k.shape[-1:] == (4,) and k.dtype.kind in "iuf" and np.isfinite(k).all(),
            "four finite real wave numbers required")
    k = k.astype(float,copy=False)
    sine = np.hypot.reduce(np.sin(k / 2), axis=-1) / 2
    cosine = np.hypot.reduce(np.cos(k / 2), axis=-1) / 2
    distance = 2 * np.arcsin(np.minimum(sine, cosine))
    return np.where(sine <= cosine, distance, np.pi - distance)


def mobile_weights(angles):
    """Trace and sharp-slot weights of the cyclic subspace generated by the equal coin."""
    k = np.asarray(angles)
    require(k.shape == (4,) and k.dtype.kind in "iuf" and np.isfinite(k).all(),
            "one finite real four-momentum required")
    k = k.astype(float,copy=False)
    phase = np.exp(1j * np.repeat(k, 2) * np.tile([1,-1], 4))
    equal = np.ones(8) / np.sqrt(8)
    image = phase * equal
    # Only at an exact sampled endpoint may the two cyclic vectors be identified.
    overlap = np.cos(k).mean()
    orthogonal = image - overlap * equal
    if np.all(np.remainder(k, 2*np.pi) == 0) or np.all(np.remainder(k, 2*np.pi) == np.pi):
        return 1, abs(equal)**2
    norm = np.hypot.reduce(abs(orthogonal))
    require(norm > 0, "unresolved cyclic plane")
    return 2, abs(equal)**2 + abs(orthogonal/norm)**2


def stopping_law(reading, cap):
    """Fair published ticks. Timeout is an outcome on the original denominator."""
    require(type(reading) is int and type(cap) is int and min(reading,cap) >= 0, "invalid clock window")
    pmf = np.zeros(cap+1)
    if reading == 0:
        pmf[0] = 1
        return pmf, 0.0
    if reading > cap:
        return pmf, 1.0
    # Count all binary prefixes with integer arithmetic. A rare timeout can be
    # representable even when subtracting the rounded first-hit sum gives zero.
    live = 1 << (reading-1)
    first_hits = 1
    for n in range(reading, cap+1):
        pmf[n] = first_hits / (1 << n)
        live = 2*live - first_hits
        first_hits = first_hits*n // (n-reading+1)
    return pmf, live / (1 << cap)


def scalar_kernel(shape, order, position, periods):
    """Equal-coin source/receiver, spatial delta launch, one private Fourier order."""
    shape, position, periods = map(np.asarray, (shape,position,periods))
    periods = np.atleast_1d(periods)
    require(shape.shape == (4,) and shape.dtype.kind in "iu" and (shape > 0).all(),
            "four positive lattice sizes required")
    require(position.shape == (3,) and position.dtype.kind in "iu", "three integer site coordinates required")
    require(isinstance(order,(int,np.integer)) and not isinstance(order,(bool,np.bool_)),
            "integer private Fourier order required")
    require(periods.ndim == 1 and periods.dtype.kind in "iu" and (periods >= 0).all(),
            "nonnegative integer period indices required")
    shape = tuple(map(int,shape))
    position = position % shape[:3]
    order = int(order) % shape[3]
    modes = np.indices(shape[:3]).reshape(3, -1).T
    spatial = 2*np.pi * modes / np.asarray(shape[:3])
    compact = np.full(len(modes), 2*np.pi*order/shape[3])
    phase = eigenphase(np.column_stack((spatial, compact)))
    translated = np.exp(1j * (spatial @ position))
    return (np.cos(np.outer(periods, phase)) @ translated) / prod(shape[:3])


def refinement():
    """Fixed physical time one. Absolute match probabilities include both heralds."""
    rows = []
    for n in (16, 32, 64, 128):
        h = 1/n
        for mode in ((1,0,0,0), (1,-1,2,1), (0,0,0,-2)):
            momentum = 2*np.pi*np.array(mode)
            omega = np.linalg.norm(momentum)/2
            micro = eigenphase(h*momentum)
            x = h*omega
            require(x <= 1 and abs(micro-x) <= x**3/4, "phase outside uniform bound")
            target = np.cos(omega)**2 / 16
            fixed = np.cos(n*micro)**2 / 16
            # E exp(2i E N) for the time of the (n/2)-th fair publication.
            z = np.exp(2j*micro)
            clocked = (1+((z/(2-z))**(n//2)).real) / 32
            spatial_budget = n*x**3/4
            clock_budget = omega**2*h
            require(abs(fixed-target) <= spatial_budget/16 and
                    abs(clocked-target) <= (spatial_budget+clock_budget)/16, "record outside transfer bound")
            rows.append(dict(N=n, mode=list(mode), fixed=float(fixed), clocked=float(clocked),
                             continuum=float(target), fixed_error=float(abs(fixed-target)),
                             clock_error=float(abs(clocked-target)), fixed_bound=float(spatial_budget/16),
                             clock_bound=float((spatial_budget+clock_budget)/16)))
    return rows
