"""The port response of one cell under the contrast-memory law, for one load and for the bound pair.

Derivation and audit on the operators of the law; no observer reads these matrices. A port service is a weak
operation by the observer of one port that lasts long against the inverse level spacings; it acts through its part
that is diagonal in the levels. The response space is a triplet `3` and a triplet `3'` of the rotations of the
cell, both odd under the antipodal map: for one load the slow and the fast port level of `H_1 = L/2 + 6 kappa`,
for the bound pair its two lowest odd triplets. A direction is visible in records when it differs from the common
phase, which changes no record probability.

The theory's gauge paper asks for twelve port generators that are independent, closed under commutators, with a
positive trace form and with the rotations of the cell acting through them. The plain services give seventeen
(two copies of su(3) and one common number). One declared service per port,
`G_p = (1/2){n_p, E_top - H_1} + J_p` with `E_top = (5 + sqrt5)/2` and `J_p` the twist round the port, gives twelve.
"""
from __future__ import annotations

import itertools
import math

import numpy as np
from scipy.linalg import logm

from model.executable_model import carrier as cr
from .common import clean
from .sectors import PairSector

TOL = 1e-9
S5 = math.sqrt(5)
PHI = (1 + S5) / 2


def cell_setup():
    car = cr.cell()
    A = car.adjacency().toarray()
    w, V = np.linalg.eigh(A)
    bands = {}
    for name, val in (('1', 5.0), ('3', S5), ('5', -1.0), ("3'", -S5)):
        bands[name] = V[:, np.flatnonzero(np.abs(w - val) < 1e-9)]
    perms = cr.automorphisms(car.seams)
    proper = []
    for p in perms:
        Pi = np.zeros((12, 12))
        Pi[list(p), range(12)] = 1
        if np.linalg.det(bands['3'].T @ Pi @ bands['3']) > 0:
            proper.append((p, Pi))
    return car, A, bands, perms, proper


def twist(A, V3, proper, p):
    """Circulation round the five neighbours of port `p`, counterclockwise seen from outside: Hermitian, odd
    under reversal of the evolution parameter."""
    ring = [q for q in range(12) if A[p, q]]
    for perm, Pi in proper:
        if perm[p] != p or perm == tuple(range(12)):
            continue
        R = V3.T @ Pi @ V3
        if abs(np.trace(R) - (1 + 2 * math.cos(2 * math.pi / 5))) > 1e-6:
            continue
        axis = np.array([R[2, 1] - R[1, 2], R[0, 2] - R[2, 0], R[1, 0] - R[0, 1]])
        if axis @ V3[p] > 0:
            J = np.zeros((12, 12), complex)
            for q in ring:
                J[perm[q], q] += 1j
                J[q, perm[q]] -= 1j
            return J, perm
    raise RuntimeError('no rotation about the port')


def local_basis(A, p, perm):
    """Hermitian operators at port `p` that the rotations about its axis leave unchanged."""
    ring = [q for q in range(12) if A[p, q]]
    e = np.eye(12)
    return {'load of the port': np.outer(e[p], e[p]),
            'load of its ring': sum(np.outer(e[q], e[q]) for q in ring),
            'exchange port-ring': sum(np.outer(e[p], e[q]) + np.outer(e[q], e[p]) for q in ring),
            'exchange along the ring': sum(np.outer(e[perm[q]], e[q]) + np.outer(e[q], e[perm[q]]) for q in ring),
            'second exchange along the ring': sum(np.outer(e[perm[perm[q]]], e[q]) + np.outer(e[q], e[perm[perm[q]]])
                                                  for q in ring)}


def response(G, Va, Vb):
    D = np.zeros((6, 6), complex)
    D[:3, :3] = -1j * (Va.conj().T @ G @ Va)
    D[3:, 3:] = -1j * (Vb.conj().T @ G @ Vb)
    return D


def realvec(M):
    return np.concatenate([M.real.ravel(), M.imag.ravel()])


def unvec(v):
    return (v[:36] + 1j * v[36:]).reshape(6, 6)


def span_basis(mats, tol=TOL):
    if not mats:
        return np.zeros((0, 72))
    X = np.array([realvec(m) for m in mats])
    _, s, vt = np.linalg.svd(X, full_matrices=False)
    return vt[s > tol * max(1.0, s[0])]


def closure(mats):
    """Real Lie algebra generated by anti-Hermitian 6 x 6 matrices: an orthonormal basis."""
    basis = span_basis(mats)
    while True:
        elems = [unvec(v) for v in basis]
        bigger = span_basis(elems + [a @ b - b @ a for a, b in itertools.combinations(elems, 2)])
        if len(bigger) == len(basis):
            return basis
        basis = bigger


def centre(basis):
    elems = [unvec(v) for v in basis]
    if not elems:
        return 0
    M = np.array([np.concatenate([realvec(a @ b - b @ a) for a in elems]) for b in elems]).T
    s = np.linalg.svd(M, compute_uv=False)
    return int(np.sum(s < 1e-8)) + max(0, len(elems) - len(s))


def embed(M, i):
    Z = np.zeros((6, 6), complex)
    Z[i:i + 3, i:i + 3] = M[i:i + 3, i:i + 3]
    return Z


def describe(mats):
    b = closure(mats)
    elems = [unvec(v) for v in b]
    with_phase = span_basis(elems + [1j * np.eye(6)])
    return {'rank': len(span_basis(mats)), 'closure': len(b), 'centre': centre(b),
            'on_first_triplet': len(span_basis([embed(m, 0) for m in elems])),
            'on_second_triplet': len(span_basis([embed(m, 3) for m in elems])),
            'visible_in_records': len(b) - (1 if len(with_phase) == len(b) else 0)}


def one_load():
    car, A, bands, perms, proper = cell_setup()
    if len(perms) != 120 or len(proper) != 60:
        raise ValueError('cell symmetry group has wrong automorphism counts')
    V3, V3p = bands['3'], bands["3'"]
    H1 = (5 * np.eye(12) - A) / 2
    top = (5 + S5) / 2
    tw, basis_ops = {}, {}
    for p in range(12):
        tw[p], perm = twist(A, V3, proper, p)
        basis_ops[p] = local_basis(A, p, perm)
    e = np.eye(12)
    loads = [response(basis_ops[p]['load of the port'], V3, V3p) for p in range(12)]
    exchanges = [response(0.5 * np.outer(e[a] - e[b], e[a] - e[b]), V3, V3p) for a, b in car.seams]
    twists = [response(tw[p], V3, V3p) for p in range(12)]
    menus = {'port loads': describe(loads), 'seam exchanges': describe(exchanges), 'port twists': describe(twists),
             'port load + twist': describe([a + b for a, b in zip(loads, twists)]),
             'all plain services': describe(exchanges + loads + twists)}

    def coeffs(G, V, p):
        M = (V.T @ G @ V).real
        w = V[p] / np.linalg.norm(V[p])
        a1 = float(w @ M @ w)
        return a1, float((np.trace(M) - a1) / 2)

    lock = {name: {'slow': coeffs(G, V3, 0), 'fast': coeffs(G, V3p, 0)} for name, G in basis_ops[0].items()}
    conj = True
    for entry in lock.values():
        for s, f in zip(entry['slow'], entry['fast']):
            x, y = (s + f) / 2, (s - f) / (2 * S5)
            conj &= abs(x * 240 - round(x * 240)) < 1e-9 and abs(y * 240 - round(y * 240)) < 1e-9

    def weighted(p):
        n_p = basis_ops[p]['load of the port']
        W = top * np.eye(12) - H1
        return 0.5 * (n_p @ W + W @ n_p)

    D = [response(weighted(p), V3, V3p) + response(tw[p], V3, V3p) for p in range(12)]
    menus['weighted port load + twist'] = describe(D)
    menus['weighted port load alone'] = describe([response(weighted(p), V3, V3p) for p in range(12)])
    gram = np.linalg.eigvalsh(np.array([[-np.trace(a @ b).real for b in D] for a in D]))
    X = np.array([realvec(m) for m in D]).T
    worst = 0.0
    for a, b in itertools.combinations(D, 2):
        c = realvec(a @ b - b @ a)
        coef, *_ = np.linalg.lstsq(X, c, rcond=None)
        worst = max(worst, float(np.linalg.norm(X @ coef - c)))
    cov, inner = 0.0, 0.0
    for perm, Pi in proper:
        U = np.zeros((6, 6))
        U[:3, :3] = V3.T @ Pi @ V3
        U[3:, 3:] = V3p.T @ Pi @ V3p
        for p in range(12):
            cov = max(cov, float(np.abs(U @ D[p] @ U.T - D[perm[p]]).max()))
        g = np.zeros((6, 6), complex)
        g[:3, :3] = logm(U[:3, :3]).real
        g[3:, 3:] = logm(U[3:, 3:]).real
        coef, *_ = np.linalg.lstsq(X, realvec(g), rcond=None)
        inner = max(inner, float(np.linalg.norm(X @ coef - realvec(g))))
    total = sum(D)
    twelve = {'rank': int(np.linalg.matrix_rank(X, tol=1e-9)), 'gram_smallest': float(gram[0]),
              'gram_largest': float(gram[-1]), 'brackets_checked': 66, 'worst_bracket_residual': worst,
              'covariance_identities': len(proper) * 12, 'worst_covariance_residual': cov,
              'rotation_generators_in_span_residual': inner,
              'sum_slow': float((total[:3, :3] / (-1j)).real.trace() / 3),
              'sum_fast': float((total[3:, 3:] / (-1j)).real.trace() / 3)}
    return {'menus': menus, 'lock': lock, 'fast_is_conjugate_of_slow': bool(conj), 'twelve': twelve}


def second_quantized(ps, G):
    """A one-load operator on the sector of two loads; terms that would put both loads on one port are dropped."""
    M = np.zeros((ps.P, ps.P), complex)
    for i in range(ps.P):
        a, b = int(ps.aa[i]), int(ps.bb[i])
        for x, other in ((a, b), (b, a)):
            for y in range(12):
                if G[y, x] != 0 and y != other:
                    M[ps.index(y, other), i] += G[y, x]
    return M


def pair_levels(ps, R5, Jm, kappa):
    H = ps.hamiltonian(kappa).toarray()
    w, U = np.linalg.eigh(H)
    out, i = [], 0
    while i < len(w):
        j = i
        while j < len(w) and abs(w[j] - w[i]) < 1e-7:
            j += 1
        V, d = U[:, i:j], j - i
        name = {1: '1', 4: '4', 5: '5'}.get(d, str(d))
        if d == 3:
            name = '3' if abs(float(np.trace(V.T @ R5 @ V)) - PHI) < 1e-6 else "3'"
        out.append({'E': float(w[i]), 'dim': d, 'type': name,
                    'parity': int(round(float(np.trace(V.T @ Jm @ V)) / d)),
                    'pair_on_a_seam': float((V[ps.adjacent] ** 2).sum() / d), 'V': V})
        i = j
    return H, out


def bound_pair():
    car, A, bands, perms, proper = cell_setup()
    V3 = bands['3']
    ps = PairSector(car)

    def on_pairs(perm):
        M = np.zeros((ps.P, ps.P))
        for i in range(ps.P):
            M[ps.index(perm[ps.aa[i]], perm[ps.bb[i]]), i] = 1
        return M

    five = next(p for p, Pi in proper if p[0] == 0 and
                abs(np.trace(V3.T @ Pi @ V3) - (1 + 2 * math.cos(2 * math.pi / 5))) < 1e-6)
    A2 = A @ A
    anti = next(p for p in perms if all(p[q] != q and not A[q, p[q]] and A2[q, p[q]] == 0 for q in range(12)))
    R5, Jm = on_pairs(five), on_pairs(anti)
    e = np.eye(12)
    load, tw = {}, {}
    for p in range(12):
        J, _ = twist(A, V3, proper, p)
        tw[p] = second_quantized(ps, J)
        load[p] = second_quantized(ps, np.outer(e[p], e[p]))
    services = {}
    for kappa in (8.0, 2.0, 1.0, 1 / PHI):
        H, lv = pair_levels(ps, R5, Jm, kappa)
        a = next(x for x in lv if x['type'] == '3' and x['parity'] == -1)
        b = next(x for x in lv if x['type'] == "3'" and x['parity'] == -1)
        band_top = max(x['E'] for x in lv if x['pair_on_a_seam'] > 0.5)
        L = [response(load[p], a['V'], b['V']) for p in range(12)]
        T = [response(tw[p], a['V'], b['V']) for p in range(12)]
        lines = {'port loads': describe(L), 'port twists': describe(T),
                'port load + twist': describe([x + y for x, y in zip(L, T)])}
        for ref_name, ref in (("own 3' level", b['E']), ('top of the bound levels', band_top)):
            W = ref * np.eye(ps.P) - H
            Wd = [response(0.5 * (load[p] @ W + W @ load[p]), a['V'], b['V']) for p in range(12)]
            lines['load weighted from the ' + ref_name + ' + twist'] = describe([x + y for x, y in zip(Wd, T)])
        services[f'{kappa:.6f}'] = {'E3': a['E'], 'E3prime': b['E'], 'menus': lines}
    # coupling one: the triplet levels and their response to the load of one port
    _, lv = pair_levels(ps, R5, Jm, 1.0)
    exact = {'2 - sqrt5': 2 - S5, '(7 - sqrt5)/2': (7 - S5) / 2, '2 + sqrt5': 2 + S5, '(7 + sqrt5)/2': (7 + S5) / 2}
    coupling_one = []
    for x in lv:
        if x['dim'] != 3:
            continue
        ev = np.linalg.eigvalsh(x['V'].T @ load[0].real @ x['V'])
        coupling_one.append({'type': x['type'], 'E': x['E'],
                             'closed_form': next((k for k, v in exact.items() if abs(v - x['E']) < 1e-10), None),
                             'load_response': [float(y) for y in ev],
                             'twist_response_norm': float(np.linalg.norm(x['V'].T @ tw[0] @ x['V'], 2)),
                             'pair_on_a_seam': x['pair_on_a_seam']})
    spread = {}
    for kappa in (0.999, 1.001):
        _, lv2 = pair_levels(ps, R5, Jm, kappa)
        b = next(x for x in lv2 if x['type'] == "3'" and x['parity'] == -1)
        ev = np.linalg.eigvalsh(b['V'].T @ load[0].real @ b['V'])
        spread[str(kappa)] = float(ev[-1] - ev[0])
    # the lowest pair level against the four port levels
    Aev, Avec = np.linalg.eigh(A)
    proj = {}
    for name, val in (('1', 5.0), ('3', S5), ('5', -1.0), ("3'", -S5)):
        idx = np.flatnonzero(np.abs(Aev - val) < 1e-9)
        proj[name] = Avec[:, idx] @ Avec[:, idx].T
    weights = {}
    for kappa in (0.0, 0.3, 1 / PHI, 1.0, 8.0):
        w, U = np.linalg.eigh(ps.hamiltonian(kappa).toarray())
        Psi = np.zeros((12, 12))
        Psi[ps.aa, ps.bb] = U[:, 0]
        Psi = Psi + Psi.T
        Psi /= np.linalg.norm(Psi) * np.sign(Psi.sum())
        weights[f'{kappa:.6f}'] = {k: float(np.trace(P @ Psi) / np.trace(P)) for k, P in proj.items()}
    k = 1 / PHI
    return {'services': services, 'coupling_one': coupling_one, 'coupling_one_neighbour_spread': spread,
            'lowest_level_weights': weights,
            'golden_coupling': {'kappa': k, 'pair_on_seam_cost': 4 - 2 * k, 'two_slow_loads_cost': 5 - S5}}


def run(full=False):
    return clean({'one_load': one_load(), 'bound_pair': bound_pair()})


if __name__ == '__main__':
    import json
    print(json.dumps(run(), indent=1))
