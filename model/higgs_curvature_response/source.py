def _inputs(w):
    return ActionInputs(
        s.sqrt(2)*w, s.Rational(3, 5), s.Rational(4, 5), s.S.One, s.Rational(1, 4),
        s.Matrix([[1, s.I/3, 0], [0, 2, 0], [0, 0, 3]]),
        s.diag(s.Rational(1, 2), s.Rational(3, 2), s.Rational(5, 2)),
        s.Matrix([[1, s.Rational(1, 4), 0], [s.Rational(1, 4), 2, 0], [0, 0, 4]]),
        ('exact supplied finite action control; no empirical parameter fit',),
        energy_unit='one common supplied model energy unit')


def higgs_variation(f, *, Fstar=s.Rational(5, 2), xi=s.Rational(1, 6), w=s.S.One):
    """Realize a polynomial deltaF using the same doublet's neutral component."""
    f = polynomial(f).as_expr()
    Fstar, xi, w = (exact(value, positive=True) for value in (Fstar, xi, w))
    parameter = s.Symbol('variation_parameter', real=True)
    H = s.Matrix([0, w-parameter*f/(2*xi*w)])
    norm = s.expand((H.H*H)[0])
    F0 = Fstar+xi*w*w
    curvature_coefficient = s.expand(F0-xi*norm)
    if s.simplify(s.diff(curvature_coefficient, parameter).subs(parameter, 0)-f) != 0:
        raise ArithmeticError('scalar variation is not generated by the same Higgs norm')
    return H, curvature_coefficient, parameter


@lru_cache(maxsize=1)
def certificate():
    _, fundamental, currents, _, channels = action._representation()
    equations = 0
    for generator in fundamental:
        higgs = generator[3:, 3:]
        if any(s.simplify(v) != 0 for v in higgs.H+higgs):
            raise ArithmeticError('actual Higgs norm is not current invariant')
    for name, row in channels.items():
        for generator, current in zip(fundamental, currents, strict=True):
            higgs = generator[3:, 3:]
            if row['conjugate_Higgs']:
                higgs = -higgs.T
            for k in range(2):
                tensor = row['components'][k]
                residual = current.T*tensor+tensor*current+sum(
                    (higgs[j, k]*row['components'][j] for j in range(2)), s.zeros(15))
                if any(s.expand(v) != 0 for v in residual):
                    raise ArithmeticError('same-current Higgs/Yukawa source equation failed')
                equations += 1
    inputs = _inputs(s.S.One)
    K1, K2 = mass_kernel(inputs), mass_kernel(_inputs(s.Rational(6, 5)))
    if K2 != s.Rational(6, 5)*K1 or K1 == s.zeros(45):
        raise ArithmeticError('actual full Higgs mass kernel lost its norm dependence')
    if (inputs.Yu.H*inputs.Yu)*(inputs.Yd.H*inputs.Yd) == (inputs.Yd.H*inputs.Yd)*(inputs.Yu.H*inputs.Yu):
        raise ArithmeticError('generic noncommuting family control became diagonal')
    x, y, z = COORDINATES
    f = 2+x+x*x+2*y*z-s.Rational(3, 5)*z*z+x*y*z
    H, F, parameter = higgs_variation(f)
    radius, limit = s.Rational(1, 2), s.Rational(1, 100)
    f_bound = sum(abs(coefficient)*radius**sum(powers) for powers, coefficient in polynomial(f).terms())
    positive_lower = s.Rational(5, 2)-limit*f_bound-limit**2*f_bound**2/(4*s.Rational(1, 6))
    if positive_lower <= 0:
        raise ArithmeticError('finite two-sided Higgs variation leaves positive curvature coefficient')
    return {'actual_internal_dimension': 15, 'actual_current_count': len(currents),
            'same_current_Higgs_equations_checked': equations,
            'full_family_mass_kernel_dimension': 45,
            'mass_kernel_norm_scaling_exact': True,
            'nonzero_Yukawa_channels': sorted(channels),
            'family_Gram_commutator_nonzero': True,
            'kernel_norm_squared_exact': str(s.simplify(s.trace(K1.H*K1))),
            'Higgs_norm': 'X=Hdagger H in the retained two-component representation',
            'F0': '8/3', 'xi': '1/6', 'Fstar': '5/2', 'w': '1',
            'deltaF_polynomial': str(f),
            'neutral_Higgs_component': str(H[1]),
            'curvature_coefficient_exact': str(F),
            'variation_parameter': str(parameter),
            'radius_for_positive_control': str(radius),
            'two_sided_parameter_bound': str(limit),
            'deltaF_absolute_upper': str(f_bound),
            'F_positive_lower': str(positive_lower),
            'curvature_extension_and_xi_are_supplied': True,
            'empirical_calibration_used': False,
            'native_curved_field_execution_claimed': False,
            'source_entropy_or_stationarity_selected': False}
