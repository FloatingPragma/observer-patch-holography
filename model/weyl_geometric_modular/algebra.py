"""Exact source frames, stress identities and the modular spinor correction."""
from functools import lru_cache
from itertools import product
import sympy as s

VALLEYS = tuple(product((0, 1), repeat=3))


def pauli():
    return (s.Matrix([[0, 1], [1, 0]]), s.Matrix([[0, -s.I], [s.I, 0]]), s.diag(1, -1))


def frame(valley):
    if type(valley) is not tuple or len(valley) != 3 or any(type(b) is not int or b not in (0, 1) for b in valley):
        raise ValueError('three exact binary valley coordinates required')
    signs = tuple((-1)**b for b in valley)
    chi = -signs[0]*signs[1]*signs[2]
    rotation = tuple(-chi*value for value in signs)
    lift = s.eye(2) if rotation == (1, 1, 1) else s.I*pauli()[rotation.index(1)]
    return signs, chi, lift


def dirac():
    alpha = tuple(s.diag(-matrix, matrix) for matrix in pauli())
    beta = s.zeros(2).row_join(s.eye(2)).col_join(s.eye(2).row_join(s.zeros(2)))
    return alpha, (beta, *(beta*matrix for matrix in alpha))


def zero(matrix):
    return all(s.expand(value) == 0 for value in matrix)


@lru_cache(maxsize=1)
def source_frames():
    rows = []
    for valley in VALLEYS:
        signs, chi, lift = frame(valley)
        if lift.adjoint()*lift != s.eye(2) or lift.det() != 1:
            raise ArithmeticError('source spin frame is not special unitary')
        for j, sigma in enumerate(pauli()):
            if lift.adjoint()*(-signs[j]*sigma)*lift != chi*sigma:
                raise ArithmeticError('source principal symbol was changed')
        rows.append({'valley': list(valley), 'chirality': chi,
                     'lift': [[str(x) for x in row] for row in lift.tolist()]})
    _, gamma = dirac()
    eta = (1, -1, -1, -1)
    for mu, nu in product(range(4), repeat=2):
        if gamma[mu]*gamma[nu]+gamma[nu]*gamma[mu] != 2*eta[mu]*int(mu == nu)*s.eye(4):
            raise ArithmeticError('Lorentz Clifford identity failed')
    return {'rows': rows, 'Weyl_fields': 8, 'each_chirality': 4,
            'Dirac_pairs': 4, 'Clifford_identities': 16,
            'unitary_source_frames': 8,
            'time_coordinate': 'x0=v*t', 'geometry_signature': '(-,+,+,+)',
            'gamma_signature': '(+,-,-,-)',
            'signature_conversion': 'g=-eta; two-lowered stress and null cone unchanged'}


def stress_kernel(mu, nu, p, q, *, symmetric=True):
    """Cross-wave coefficient with contravariant momenta, before spinor pairing."""
    if type(mu) is not int or type(nu) is not int or not 0 <= mu < 4 or not 0 <= nu < 4:
        raise ValueError('Lorentz indices must be integers in [0,3]')
    if len(p) != 4 or len(q) != 4:
        raise ValueError('four momenta required')
    _, gamma = dirac()
    first = gamma[mu]*(p[nu]+q[nu])
    return (first+gamma[nu]*(p[mu]+q[mu]))/4 if symmetric else first/2


@lru_cache(maxsize=1)
def stress_certificate():
    p = s.symbols('p0:4', real=True); q = s.symbols('q0:4', real=True)
    _, gamma = dirac(); eta = (1, -1, -1, -1)
    slashp = sum((eta[j]*p[j]*gamma[j] for j in range(4)), s.zeros(4))
    slashq = sum((eta[j]*q[j]*gamma[j] for j in range(4)), s.zeros(4))
    p2 = sum(eta[j]*p[j]**2 for j in range(4)); q2 = sum(eta[j]*q[j]**2 for j in range(4))
    for mu, nu in product(range(4), repeat=2):
        if stress_kernel(mu, nu, p, q) != stress_kernel(nu, mu, p, q):
            raise ArithmeticError('stress symmetry failed')
    for nu in range(4):
        divergence = sum((eta[mu]*(p[mu]-q[mu])*stress_kernel(mu, nu, p, q)
                          for mu in range(4)), s.zeros(4))
        # The remainder is in the ideal generated by the two mass shells.
        expected = ((p2*slashq-q2*slashp)*(p[nu]+q[nu])
                    +(p2-q2)*slashp*gamma[nu]*slashq)/4
        if not zero(slashp*divergence*slashq-expected):
            raise ArithmeticError('on-shell Ward identity failed')
    trace = sum((eta[mu]*stress_kernel(mu, mu, p, q) for mu in range(4)), s.zeros(4))
    if not zero(slashp*trace*slashq-(p2*slashq+q2*slashp)/2):
        raise ArithmeticError('on-shell flat-space trace identity failed')
    return {'symmetric_components': 16, 'Ward_polynomial_identities': 4,
            'trace_polynomial_identities': 1,
            'equations_used': 'bar(u(p))slash(p)=0 and slash(q)u(q)=0',
            'Einstein_equation_used': False,
            'operator_scope': 'vacuum-normal-ordered distributions on smooth finite-particle vectors',
            'curved_space_trace_anomaly_excluded_from_claim': True}


@lru_cache(maxsize=1)
def projector_certificate():
    """Prove that the complete conformal charge preserves the filled sea."""
    p = s.symbols('p1:4', real=True); r = s.symbols('r', positive=True)
    def on_radius(matrix):
        # Entries become polynomials after clearing their common denominator.
        return all(s.rem(s.Poly(s.expand(v*r**4), r),
                         s.Poly(r*r-sum(x*x for x in p), r)).is_zero for v in matrix)
    for valley in VALLEYS:
        signs, _, _ = frame(valley)
        alpha = tuple(-signs[j]*pauli()[j] for j in range(3))
        h = sum((alpha[j]*p[j] for j in range(3)), s.zeros(2))
        projector = (s.eye(2)+h/r)/2
        derivative = tuple((alpha[j]/r-h*p[j]/r**3)/2 for j in range(3))
        for j in range(3):
            if not on_radius(2*h*derivative[j]+alpha[j]*projector-projector*alpha[j]):
                raise ArithmeticError('derivative coefficient mixes particle/hole bands')
        if not on_radius(-h*h/r**3+sum((alpha[j]*derivative[j] for j in range(3)), s.zeros(2))):
            raise ArithmeticError('zeroth coefficient mixes particle/hole bands')
    return {'valleys': 8, 'first_derivative_identities': 24,
            'zeroth_derivative_identities': 8,
            'complete_conformal_charge_commutes_with_filled_sea_projector': True,
            'ball_only_cutoff_charge_claimed_selfadjoint': False}


def weighted_generator(half_gradient=s.Rational(1, 2)):
    """Return coefficients of q/(2*pi)=w*h-i*half_gradient*alpha.grad(w)."""
    if type(half_gradient) is not int and not isinstance(half_gradient, s.Rational):
        raise ValueError('exact rational gradient coefficient required')
    x = s.symbols('x1:4', real=True); R = s.symbols('R', positive=True)
    w = (R*R-sum(z*z for z in x))/(2*R)
    alpha, _ = dirac()
    first = tuple(-s.I*w*a for a in alpha)
    lower = -s.I*half_gradient*sum((alpha[j]*s.diff(w, x[j]) for j in range(3)), s.zeros(4))
    # D*= -A_j^* d_j -(d_j A_j^*)+B*, so this is D*-D.
    defect = lower.adjoint()-lower-sum((first[j].adjoint().diff(x[j]) for j in range(3)), s.zeros(4))
    return {'first': first, 'lower': lower, 'formal_adjoint_defect': defect,
            'coordinates': x, 'radius': R, 'weight': w}


def certificate():
    if not zero(weighted_generator()['formal_adjoint_defect']):
        raise ArithmeticError('correct modular charge is not formally symmetric')
    if zero(weighted_generator(0)['formal_adjoint_defect']):
        raise ArithmeticError('missing spinor correction was not detected')
    return {'source': source_frames(), 'stress': stress_certificate(),
            'vacuum_projector': projector_certificate(),
            'required_gradient_coefficient': '1/2',
            'missing_gradient_negative_control_rejected': True}
