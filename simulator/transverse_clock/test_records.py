@pytest.mark.parametrize("phase,digest", [
    (1, "ba03f8c8da5774c9d99ec214dcd71b296d0642d1415b08b8e4487889e24238aa"),
    (1j, "ae06d6d6d9c28a3c0c86df6ab6061d806fddfeb4871e850d52007cdb0f149529"),
])
def test_pinned_openwave_gate(phase, digest):
    # Generated by full_step from kernel_blob in protocol.json, on every slot and address.
    indices = np.arange(3**4 * 8).reshape((3,)*4 + (8,))
    state = (indices%7 - 3) + 1j*((indices//3)%5 - 2)
    freq = 2*np.pi*np.fft.fftfreq(3)
    shifts = kernel.multipliers(np.stack(np.meshgrid(*[freq]*4, indexing="ij"), axis=-1))
    axes = (0, 1, 2, 3)
    packed = np.fft.fftn(state, axes=axes)
    check = hashlib.sha256()
    for _ in range(7):
        state = 8*kernel.real_step(state, phase)
        packed = 8*kernel.step(packed, shifts, phase)
        np.testing.assert_allclose(np.fft.ifftn(packed, axes=axes), state, atol=2e-8, rtol=1e-12)
        parts = np.stack((state.real, state.imag), axis=-1)
        np.testing.assert_array_equal(parts, np.rint(parts))
        check.update(parts.astype("<i8").tobytes())
    assert check.hexdigest() == digest


@pytest.mark.parametrize("phase", [1, 1j])
@pytest.mark.parametrize("route", [(0, -3, 0), (2, -1, 0), (1, -1, 1), (0, 0, 1)])
def test_front_against_unpruned_wave(route, phase):
    state = np.zeros((9, 9, 9, 1, 8), complex)
    axis = next(j for j, n in enumerate(route) if n)
    slot = 2*axis + int(route[axis] < 0)
    state[0, 0, 0, 0] = kernel.reflect(np.eye(8)[slot])
    for _ in range(sum(map(abs, route))):
        state = kernel.real_step(state, phase)
    measured = np.linalg.norm(state[(*route, 0)])**2
    assert race.front(route, phase) == pytest.approx(measured)
    assert race.front_formula(route, phase) == pytest.approx(measured)


def test_exact_axial_tail_and_rate():
    speeds = [(3, 5), (3, 4), (1, 1)]
    waits = range(1, 10)
    tails = frontier.exact_tails(waits, speeds)
    equal = np.ones(8)/np.sqrt(8)
    state = np.zeros((25, 1, 1, 1, 8), complex)
    state[12, 0, 0, 0] = equal
    for t in waits:
        state = kernel.real_step(state)
        mass = abs(state[:, 0, 0, 0] @ equal)**2
        for a, b in speeds:
            first = math.ceil(t*a/b)
            entry = tails[str(t)][f"{a}/{b}"]
            assert int(entry["numerator"])/(4*16**t) == pytest.approx(sum(mass[12+first:]), abs=1e-16)
    u = .75
    tilt = 2*math.asinh(math.sqrt((4*u*u-1)/(1-u*u)))
    assert frontier.rate(u) == pytest.approx(2*(tilt*u-kernel.tilt_rate([tilt,0,0,0])))
    assert kernel.passive_log_bound(1024, u*1024, [tilt,0,0,0]) < -100


