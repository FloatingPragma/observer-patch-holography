def test_ring_length_and_large_local_clock_offsets():
    _, exchanges, stamps, lap = chart.stations(4, 0, [0, 4, 9])
    for wrong in (lap-1, np.array([lap]), float(lap)):
        with pytest.raises(ValueError, match="lap"):
            chart.reconstruct(exchanges, stamps, wrong)
    # Changing a clock's origin cannot change any physical interval. At this
    # origin binary64 cannot distinguish successive integer receipt ticks.
    offset = 2**58
    exchanges[:, :, 1] += offset
    stamps += offset
    coords, times, period = chart.reconstruct(exchanges, stamps, lap)
    assert period == 4 and sorted(coords) == [0, 1, 2, 3]
    np.testing.assert_array_equal(times, [0, 4, 9])
    np.testing.assert_array_equal(local_times(exchanges[0], stamps[:,0]), times)
    stamps[1,0] += 1
    with pytest.raises(ValueError, match="asynchronous"):
        chart.reconstruct(exchanges, stamps, lap)
    stamps[1,0] -= 1
    exchanges[0,2,1] += 1
    with pytest.raises(ValueError, match="third clock"):
        chart.reconstruct(exchanges, stamps, lap)
    with pytest.raises(ValueError, match="third clock"):
        local_times(exchanges[0], stamps[:,0])


def test_local_winding_against_literal_cut_and_receiver():
    size, tags, x = 12, 8, 2
    center = (3, 3)
    modes, _, initial, _ = kernel.packet(size, center, 2)
    plain = np.zeros((size, size, 8), complex)
    plain[np.ix_(modes[0]%size, modes[1]%size)] = initial
    packet = np.fft.ifft2(plain, axes=(0,1))*size
    # Signed tag is an explicit third register. Store y in [-L/2,L/2) order.
    state = np.zeros((size, size, tags, 8), complex)
    state[:, :, 0] = np.roll(packet, size//2, axis=1)
    xmodes, angles, initial = source.launch(size, center, tags)
    closed = source.exact_powers(initial, angles)
    for t in range(26):
        if t in (0, 3, 9, 18, 25):
            at = state[x, size//2]
            measured = (abs(at)**2).sum(axis=-1)/size**2
            np.testing.assert_allclose(source.aperture(closed(t), xmodes, size, x, tags), measured, atol=4e-17)
        mixed = kernel.reflect(state)
        following = np.empty_like(state)
        for slot in range(8):
            sign = 1 if slot%2 == 0 else -1
            outgoing = mixed[...,slot]
            if slot//2 == 0:
                moved = np.roll(outgoing, sign, axis=0)
            elif slot//2 == 1:
                moved = np.roll(outgoing, sign, axis=1)
                edge = 0 if sign == 1 else -1
                moved[:,edge] = np.roll(moved[:,edge], sign, axis=1)
            else:
                moved = outgoing
            following[...,slot^1] = moved
        state = following


def test_flat_bands_and_coincident_endpoints():
    angles = np.array([[0.]*4, [np.pi]*4, [1.2,.3,-.5,0.], [-.7,.9,0.,.2]])
    rng = np.random.default_rng(647)
    state = rng.normal(size=(4,8)) + 1j*rng.normal(size=(4,8))
    power = source.exact_powers(state, angles)
    for t in range(18):
        np.testing.assert_allclose(power(t), state, atol=4e-14)
        state = kernel.step(state, kernel.multipliers(angles))


def test_relay_erasure_and_authentication():
    spec = {"tag_bytes":8, "nonce_bytes":8}
    challenge = bytes(range(8))
    word = race.frame(b"key", b"session", b"?", challenge, spec)
    assert race.valid(word, b"key", b"session", b"?", spec)
    for role, session, payload in [(b"!",b"session",word),(b"?",b"old",word),
                                   (b"?",b"session",bytes([1])+word[1:])]:
        assert not race.valid(payload, b"key", session, role, spec)
    binary = np.unpackbits(np.frombuffer(word, dtype=np.uint8))
    rails = np.zeros((len(binary),2), dtype=np.int16)
    rails[np.arange(len(binary)), binary] = 2
    assert race.decode(rails) == word
    for value in (0, 1):
        rails[2] = value
        assert race.decode(rails) is None
    for bad in (rails[:-1], -rails, rails.astype(float)):
        with pytest.raises(ValueError):
            race.decode(bad)
    with pytest.raises(ValueError):
        race.forecast({}, float("nan"))


def test_bad_station_receipts_and_record_substitution(tmp_path):
    _, exchanges, stamps, lap = chart.stations(12, 0, [0,4,9])
    chart.reconstruct(exchanges, stamps, lap)
    exchanges[3,2,1] += 1
    with pytest.raises(ValueError):
        chart.reconstruct(exchanges, stamps, lap)
    rows = np.zeros((3,9), dtype=np.int64)
    rows[:,-1] = 1024
    cal, stamp, rows = report(12, 3, [0,4,9], rows)
    assert peak(rows, local_times(cal, stamp), 1024) is None
    rows[1,1] = 5000
    with pytest.raises(ValueError):
        peak(rows, local_times(cal, stamp), 1024)
    with pytest.raises(ValueError):
        source.observe(12,(3,3),0,[0,9,3],{"tag_modulus":8,"shots_per_four_volume":32})
    path = tmp_path/"raw.npz"
    np.savez_compressed(path, bins=rows)
    for mutant in ({"bins":rows+1}, {"bins":rows.astype(float)}, {"renamed":rows}):
        with pytest.raises(ValueError):
            archive(path, mutant)
    target = tmp_path/"record.json"
    target.write_text('{"r":false}', encoding="utf-8")
    with pytest.raises(ValueError):
        receipt(target, {"r":0})
